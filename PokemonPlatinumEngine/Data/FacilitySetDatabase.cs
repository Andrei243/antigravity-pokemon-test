using System;
using System.Collections.Generic;
using System.Linq;

namespace PokemonPlatinumEngine.Data;

/// <summary>Why a species of the games has no later set (plan 37 · FC1, the report's list in <c>facility-sets.json</c>).</summary>
public enum FacilitySetGapReason
{
    /// <summary>On the Frontier's banlist (<see cref="FrontierDatabase.IsBanned"/>), so no place of the frame lets it in.</summary>
    Banned,

    /// <summary>No file of Showdown's random-battle sets names it.</summary>
    NotNamed,

    /// <summary>A file names it, but no role leaves it two moves its own data can teach it that the engine runs in full.</summary>
    NoFit
}

/// <summary>A species of the games with no later set, and why.</summary>
public sealed class FacilitySetGap
{
    public string Species { get; set; } = "";
    public FacilitySetGapReason Why { get; set; }
}

/// <summary>The later sets' file (<c>Data/facility-sets.json</c>, written by <c>tools/DataImporter</c>'s <c>FacilitySets.cs</c>).</summary>
public sealed class FacilitySetData
{
    /// <summary>The sets, in National Pokédex order and each species' in its roles' order.</summary>
    public List<FrontierSetRecord> Sets { get; set; } = new();

    /// <summary>The species of the games' 1,025 with no set, in National Pokédex order.</summary>
    public List<FacilitySetGap> Without { get; set; } = new();
}

/// <summary>
/// The later sets (plan 37 · FC1; <c>docs/data-files.md</c>, "The later sets"): a battle set for each role of every
/// species of the games that Pokémon Showdown's random-battle files name, in <see cref="FrontierSetRecord"/>'s shape with
/// an <see cref="FrontierSetRecord.Ability"/> and a <see cref="FrontierSetRecord.Tier"/>, so the later battle places draw
/// their trainers from species past Platinum's 493 (<see cref="Models.Facilities.FacilityTrainers"/>). Generated by the
/// importer, never by hand: a set to correct goes in <c>tools/DataImporter/Overrides/facility-sets.json</c>.
/// </summary>
public static class FacilitySetDatabase
{
    public const string FileName = "facility-sets.json";

    /// <summary>How many tiers the sets are cut into, 1 the weakest.</summary>
    public const int Tiers = 4;

    private static readonly Lazy<FacilitySetData> data = new(() => GameDataFiles.Load<FacilitySetData>(FileName));
    private static readonly Lazy<Dictionary<string, FrontierSetRecord>> byId =
        new(() => data.Value.Sets.ToDictionary(s => s.Id, StringComparer.OrdinalIgnoreCase));

    public static IReadOnlyList<FrontierSetRecord> Sets => data.Value.Sets;
    public static IReadOnlyList<FacilitySetGap> Without => data.Value.Without;

    /// <summary>A set by its id (<c>garchomp_fast_attacker</c>); null for none.</summary>
    public static FrontierSetRecord? Get(string id) => byId.Value.GetValueOrDefault(id);

    /// <summary>A species' sets, in their roles' order.</summary>
    public static IEnumerable<FrontierSetRecord> Of(string species) => Sets.Where(s => s.Species == species);

    /// <summary>
    /// The tier of a species' random-battle level, Showdown's own measure of strength, lower the stronger (a rule of ours,
    /// <c>docs/mechanics/rulings.md</c>, "The later sets"): 4 at 78 and under, 3 to 83, 2 to 88, 1 above.
    /// </summary>
    public static int TierOfLevel(int level) => level switch
    {
        <= 78 => 4,
        <= 83 => 3,
        <= 88 => 2,
        _ => 1
    };

    /// <summary>The tier by the base stat total, where no file gives a level: 4 from 580, 3 from 500, 2 from 420, 1 under.</summary>
    public static int TierOfTotal(int total) => total switch
    {
        >= 580 => 4,
        >= 500 => 3,
        >= 420 => 2,
        _ => 1
    };
}
