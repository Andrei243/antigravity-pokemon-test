    /// Every hand-built species the data flags (<see cref="PokemonSpecies.GenderDifferences"/>) is to be here; L6 put
    /// in Kanto's 23, L7 and L8 add Johto's, Hoenn's and Sinnoh's.
    /// </summary>
    public static IReadOnlyList<string> Females { get; } = new[]
    {
        // Plan 09 · L6: Kanto
        "Venusaur", "Butterfree", "Rattata", "Raticate", "Pikachu", "Raichu", "Zubat", "Golbat", "Gloom", "Vileplume",
        "Kadabra", "Alakazam", "Doduo", "Dodrio", "Hypno", "Rhyhorn", "Rhydon", "Goldeen", "Seaking", "Scyther",
