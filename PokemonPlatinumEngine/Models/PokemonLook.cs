    /// <summary>
    /// Every model with a female look (plan 09 · L8): the sculpted ones of <see cref="Females"/>, and beside them any
    /// species the data flags (<see cref="PokemonSpecies.GenderDifferences"/>) whose females are no form of their own
    /// (<c>Meowstic-Female</c> is one, and is a model of its own already), whose female is generated by rule where
    /// nobody has sculpted her. Made once, the first time it is asked.
    /// </summary>
    private static readonly Lazy<HashSet<string>> FemaleSet = new(() =>
    {
        var set = new HashSet<string>(Females, StringComparer.OrdinalIgnoreCase);
        foreach (var s in Data.PokemonDatabase.Everyone())
            if (s.GenderDifferences && s.Form(s.Name + "-Female") == null) set.Add(s.Name);
        return set;
    });

    /// <summary>Whether a model (a species' or a form's own name) has a female look of its own.</summary>
    public static bool HasFemale(string modelName) => FemaleSet.Value.Contains(modelName);

    /// <summary>Whether a look name is a shiny one.</summary>
    public static bool IsShiny(string name) => name.EndsWith(ShinySuffix, StringComparison.Ordinal);

    /// <summary>Whether a look name is a female one.</summary>
    public static bool IsFemale(string name) => Unshined(name).EndsWith(FemaleSuffix, StringComparison.Ordinal);

    /// <summary>The look with its shiny colours taken off (<c>Pikachu+f+s</c> is <c>Pikachu+f</c>): the sculpt it is built from.</summary>
    public static string Unshined(string name) => IsShiny(name) ? name[..^ShinySuffix.Length] : name;

    /// <summary>The model's own name, with whatever look it was asked in taken off: the name the data knows.</summary>
    public static string Base(string name)
    {
        string sculpt = Unshined(name);
        return sculpt.EndsWith(FemaleSuffix, StringComparison.Ordinal) ? sculpt[..^FemaleSuffix.Length] : sculpt;
    }

    /// <summary>The shiny look of a model (a name already shiny stays as it is).</summary>
    public static string Shiny(string name) => IsShiny(name) ? name : name + ShinySuffix;

    /// <summary>A model's look, shiny or not (a female look keeps its <c>+f</c>).</summary>
    public static string Of(string modelName, bool shiny) => shiny ? Shiny(modelName) : Unshined(modelName);

    /// <summary>
    /// A model's look for a Pokémon of a gender: <c>+f</c> where it is female and the model has a female look
    /// (<see cref="HasFemale"/>), then <c>+s</c> where it is shiny.
    /// </summary>
    public static string Of(string modelName, bool female, bool shiny)
    {
        string model = Base(modelName);
        string look = female && HasFemale(model) ? model + FemaleSuffix : model;
        return shiny ? look + ShinySuffix : look;
    }
}
