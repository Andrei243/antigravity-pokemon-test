using System.Collections.Generic;

namespace PokemonPlatinumEngine.Models;

/// <summary>
/// The names a Pokémon's looks are asked for by (plan 09 · L1, L6; style guide, "Pokémon (version 2, G7)", "Shiny
/// Pokémon", "Female looks"): a model's own name (a species' or a form's, <see cref="Pokemon.ModelName"/>), then
/// <c>+f</c> for a female whose species has a female look of its own (<see cref="Females"/>), then <c>+s</c> for a
/// shiny (<c>Gyarados+s</c>, <c>Pikachu+f</c>, <c>Pikachu+f+s</c>). The models, the menu sprites and the field
/// sprites take any of them; what is read from the data (a size, a cry, a number) goes by the <see cref="Base"/>
/// name. GPU-free.
/// </summary>
public static class PokemonLook
{
    /// <summary>What a shiny look's name ends in.</summary>
    public const string ShinySuffix = "+s";

    /// <summary>What a female look's name carries after its model's name (before any <see cref="ShinySuffix"/>).</summary>
    public const string FemaleSuffix = "+f";

    /// <summary>
