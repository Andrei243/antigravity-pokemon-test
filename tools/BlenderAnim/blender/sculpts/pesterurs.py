# Pesterurs (Carpathia No. 10164) sculpted from nothing on the skeleton and clips of the game's own export of it
# (sculptkit.py), grown from Speleurs (sibling("speleurs")): its domed head and pale muzzle, its round ear with the dark
# lining, its sleepy eye under the heavy lid, its claws and paws, its shaggy locks, its crust of calcite with drips of
# short lobes mottled in beige and lavender grey, the board check.
#   blender --background --factory-startup --python sculpts/pesterurs.py -- <the export's Pesterurs.glb> <out.glb>
#
# The game has no sculptor of its own for Pesterurs: its export is a quadruped generated by rule, of which only the
# bones, the clips and the size are taken.
#
# The design, from the project's picture (docs/art/reference/gemini/carpathia/10164-Pesterurs.jpg): the great cave
# bear, sitting heavily on its rump, its forelegs straight down to enormous paws, its hind feet forward at its sides
# with their soles turned up and out (dark pads, pale claws). Coarse darker grey-brown fur, shaggy at the cheeks, the
# throat and the flanks. A steep domed forehead, small round ears, a short pale muzzle and a dark nose, a calm closed
# mouth, small kind eyes half lidded under level heavy brows. Over its shoulders and back a heavy crust of white
# calcite mottled with beige, running down its flanks in drips, and standing out of it a row of stalagmites, the
# tallest over the shoulders.
# The skeleton: body (0, 0, 0.328), head (0, -0.172, 0.414), ears (+-0.084, -0.378, 0.69), legs (+-0.139, -0.177,
# 0.274), hinds (+-0.139, 0.177, 0.274), tail (0, 0.263, 0.393). Seated, as the brief and the picture have it: the hind
# legs run forward from their joints at the hips, so the clips that swing them kick the feet.
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np
from sculptkit import Kit, ell, tube, hull, srgb, inside, unit, boxy, args, sibling

sp = sibling("speleurs")

FUR, FURDARK, MUZZLE, NOSE, MOUTH = "#6D665F", "#524C47", "#958C82", "#3F322D", "#2A221F"
PAD, CRUST, BEIGE, LAV = "#433D39", sp.CRUST, sp.BEIGE, sp.LAV
LINING, BROW = "#433E3A", "#403A36"

H = np.array([0.0, -0.375, 0.6])           # the head's middle (its bone at 0, -0.172, 0.414)
HR = np.array([0.172, 0.163, 0.163])


def body(k):
    k.add("rump", ell((0, 0.13, 0.265), (0.235, 0.24, 0.25)), FUR, "body")
    k.add("trunk", ell((0, -0.04, 0.43), (0.23, 0.24, 0.27)), FUR, "body")
    k.add("chest", ell((0, -0.2, 0.44), (0.205, 0.17, 0.23)), FUR, "body")
    k.add("hump", ell((0, -0.12, 0.6), (0.2, 0.2, 0.13)), FUR, "body")
    k.add("neck", ell((0, -0.29, 0.57), (0.165, 0.135, 0.15)), FUR, "head")
    k.add("tail", ell((0, 0.37, 0.15), (0.045, 0.04, 0.04)), FUR, "tail")


def legs(k):
    for s, nm in ((1, "R"), (-1, "L")):
        m = np.array([s, 1, 1.0])
        # the forelegs straight down from broad shoulders to enormous paws
        k.add("shoulder" + nm, ell(np.array((0.16, -0.23, 0.42)) * m, (0.12, 0.135, 0.2)), FUR, "leg" + nm)
        k.add("fore" + nm, tube([np.array(p) * m for p in [(0.165, -0.26, 0.3), (0.172, -0.29, 0.16),
                                                           (0.175, -0.315, 0.095)]], [0.098, 0.093, 0.09]), FUR,
              "leg" + nm)
        k.add("pawf" + nm, ell(np.array((0.178, -0.345, 0.042)) * m, (0.1, 0.12, 0.044)), FURDARK, "leg" + nm)
        sp.paw_claws(k, "f" + nm, np.array((0.178, -0.45, 0.05)) * m, (0, -1, 0), 0.038, 5, 0.05, 0.013, "leg" + nm)
        # the hind legs: great haunches on the ground, the shins run forward to feet set up on their heels
        k.add("haunch" + nm, ell(np.array((0.165, 0.08, 0.22)) * m, (0.135, 0.2, 0.2)), FUR, "hind" + nm)
        k.add("thigh" + nm, tube([np.array(p) * m for p in [(0.18, 0.08, 0.2), (0.21, -0.06, 0.12),
                                                            (0.23, -0.15, 0.1)]], [0.12, 0.1, 0.085]), FUR,
              "hind" + nm)
        k.add("pawh" + nm, ell(np.array((0.23, -0.205, 0.105)) * m, (0.088, 0.05, 0.1), rot=(-12, 0, 0)), FURDARK,
              "hind" + nm)
        for i in range(4):
            o = (i - 1.5) * 0.037
            base = np.array((0.23 + o, -0.235, 0.19 - 0.012 * abs(i - 1.5))) * m
            sp.claw(k, f"clawh{nm}{i}", base, (0.1 * (i - 1.5) * s, -0.55, 0.85), 0.042, 0.012, "hind" + nm, curl=0.3)
    k.paint(lambda P: inside(P[:, 2] - 0.08, 0.006) * inside(P[:, 1] + 0.2, 0.01), FURDARK, on=["fore", "pawf"])


def soles(k):
    """The hind feet's soles, turned forward: a broad dark pad and four toe pads."""
    for s in (1, -1):
        c = np.array((0.23 * s, -0.27, 0.1))
        n = unit(0, -1, 0.15)
        k.decal(c, n, (0.052, 0.046), PAD, eps=0.003, rings=12, segs=48)
        for i in range(4):
            o = (i - 1.5) * 0.034
            k.decal(np.array((0.23 * s + o, -0.23, 0.168 - 0.01 * abs(i - 1.5))), unit(0, -1, 0.35),
                    (0.015, 0.014), PAD, eps=0.003, rings=8, segs=36)


def fur(k):
    locks = [((0.14, -0.42, 0.47), (0.75, 0.1, -0.55), 0.08), ((0.16, -0.35, 0.53), (0.85, 0.25, -0.3), 0.075),
             ((0.07, -0.46, 0.43), (0.35, -0.3, -0.85), 0.065), ((0.0, -0.4, 0.41), (0.0, -0.4, -0.9), 0.07),
             ((0.17, -0.28, 0.6), (0.8, 0.45, 0.1), 0.07), ((0.14, -0.31, 0.4), (0.45, -0.3, -0.8), 0.065),
             ((0.21, -0.08, 0.36), (0.35, 0.1, -0.9), 0.065), ((0.21, 0.08, 0.42), (0.4, 0.45, -0.75), 0.06),
             ((0.22, 0.2, 0.3), (0.35, 0.6, -0.7), 0.06)]
    for i, (b, d, l) in enumerate(locks):
        bone = "head" if b[1] < -0.3 else "body"
        sp.tuft(k, f"lock{i}", b, d, l, 0.027, bone, FUR)
        sp.tuft(k, f"lockL{i}", (-b[0], b[1], b[2]), (-d[0], d[1], d[2]), l * 0.95, 0.027, bone, FUR)


def stalagmite(k, name, base, d, length, r, seed, colour=CRUST):
    """A stalagmite of calcite standing out of the crust: a flat-faced spire, a little crooked."""
    rs = np.random.RandomState(seed)
    base, d = np.array(base, float), unit(*d)
    a = unit(*np.cross(d, (0, 1.0, 0)))
    b = np.cross(d, a)
    P = []
    for t, rr in ((0.0, 1.0), (0.38, 0.62), (0.7, 0.32)):
        for j in range(6):
            th = 2 * math.pi * j / 6 + rs.uniform(-0.3, 0.3)
            P.append(base + d * length * t + (a * math.cos(th) + b * math.sin(th)) * r * rr * rs.uniform(0.85, 1.1))
    P.append(base + d * length + a * r * 0.15)
    k.add(name, hull(P), colour, "body", fuse=False, surface="shell")


def pesterurs(src, out):
    k = Kit(src, coat="fur")
    body(k)
    legs(k)
    fur(k)
    HEAD = sp.head(k, H, HR, (0, -0.13, -0.065), (0.08, 0.065, 0.062), (FUR, MUZZLE, NOSE, MOUTH),
                   dome=(0.0, -0.02, 0.09), dome_r=(0.88, 0.82, 0.68), mouth_open=False)
    sp.round_ear(k, (0.115, -0.36, 0.735), (0.045, 0.025, 0.042), (0.25, -1, 0.15), "ear{s}", FUR, LINING,
                 (0.023, 0.023))
    sp.crust(k, [((0, -0.03, 0.655), (0.2, 0.24, 0.09), 6), ((0.02, 0.14, 0.58), (0.2, 0.16, 0.09), 5),
                 ((0.03, -0.15, 0.68), (0.15, 0.12, 0.075), 5), ((0.05, 0.03, 0.7), (0.11, 0.14, 0.065), 4)],
             [((0.21, -0.07, 0.62), (0.23, -0.07, 0.53), 0.038), ((0.21, 0.1, 0.58), (0.235, 0.11, 0.5), 0.034),
              ((-0.2, -0.13, 0.62), (-0.215, -0.14, 0.54), 0.034)],
             seed=8, freq=0.55,
             cover=sp.coat_edge(-0.3, 0.32, 0.56, [(1, -0.21, 0.09, 0.026), (1, -0.08, 0.15, 0.032),
                                                    (1, 0.05, 0.08, 0.022), (1, 0.18, 0.12, 0.03),
                                                    (-1, -0.15, 0.1, 0.03), (-1, 0.05, 0.08, 0.026),
                                                    (-1, 0.2, 0.07, 0.022)]),
             cover_on=["trunk", "hump", "rump", "shoulder", "haunch", "crust"])
    # The stalagmites: a row along the back, the tallest over the shoulders, leaning back and out a little
    for i, (x, y, z, l, r, lean) in enumerate(((0.02, -0.1, 0.71, 0.15, 0.058, (0.08, 0.3, 1)),
                                               (0.11, -0.03, 0.7, 0.12, 0.05, (0.5, 0.2, 1)),
                                               (-0.09, -0.05, 0.7, 0.11, 0.048, (-0.5, 0.2, 1)),
                                               (0.04, 0.07, 0.69, 0.17, 0.06, (0.15, 0.4, 1)),
                                               (0.13, 0.15, 0.62, 0.11, 0.048, (0.55, 0.4, 1)),
                                               (-0.09, 0.16, 0.62, 0.1, 0.046, (-0.5, 0.45, 1)),
                                               (0.03, 0.24, 0.57, 0.1, 0.044, (0.1, 0.75, 0.75)))):
        stalagmite(k, f"spire{i}", (x, y, z), lean, l, r, 30 + i, colour=CRUST if i % 3 else BEIGE)
    soles(k)
    sp.brows(k, HEAD, H, (0.06, 0, 0.06), (0.42, -0.9, 0.25), (0.034, 0.01), BROW, tilt=0.0)
    E = sp.hit(HEAD, H + (0.064, -0.6, 0.018), (0, 1, 0))
    lay = sp.eye_layer(k, E, unit(0.42, -0.9, 0.1), (0.03, 0.026), sp.sleepy(FURDARK, lid=0.1, slope=0.0), FURDARK)
    k.build(voxel=0.008, band=0.005, wband=0.06)
    sp.board(k.ob)
    k.eye_states(lay)
    k.export(out)


if __name__ == "__main__":
    pesterurs(*args())
