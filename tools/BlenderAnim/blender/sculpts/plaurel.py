# Plaurel (Carpathia No. 10123) sculpted from nothing on the skeleton and clips of the game's own export of it:
#   blender --background --factory-startup --python sculpts/plaurel.py -- <the export's Plaurel.glb> <out.glb>
#
# From its picture (docs/art/reference/gemini/carpathia/10123-Plaurel.jpg) and its brief (CP-dex-3, No. 123): a round
# mat of tangled brown roots and peat, moss growing in green patches over it, a tall tuft of green reeds out of its
# top like hair (leaning a little to one side, some blades arching over), five brown cattail heads among them; in the
# front a dark hollow among the roots out of which two glowing teal eyes peek; a fringe of loose root ends hanging
# under it. The game's export is a body generated by rule: only its skeleton (root, body, head, sprout) and clips are
# used. It sits on the ground (the export's lowest is 0): the water it floats on is scenery.
#
# Written to be grown from (Plaurnaut, the floating island): the roots (`vine`, `arcs`, `dangle`), the reeds (`reed`,
# `cattail`, `tuft`), the moss (`moss`), the eyes (`teal_eye`, `lay_eyes`) and the board check (`board`) take the kit.
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np
import bpy
from sculptkit import Kit, ell, tube, blade, srgb, inside, unit, eye_look, axes, lumpy, args

ROOT, ROOT2, ROOT3 = "#7A5C40", "#8E7052", "#5E4632"      # the roots: three browns, the palest the newest
CORE, HOLLOW = "#3E3022", "#16120C"                       # the peat under them; the dark hollow the eyes look from
MOSS, MOSS2, MOSSROOT = "#5E8C34", "#7AA646", "#6E7E3C"                      # moss
REED, REED2, REED3 = "#4C8A36", "#68A646", "#3A7030"      # reed blades
CAT, STALK = "#8A6646", "#6E7E44"                         # a cattail's head and its stalk
TEAL, TEALDK, GLINT = "#5CEADA", "#1E9C92", "#F4FFFE"     # the eyes' glow, their lower shade, the glint

C = np.array([0.0, 0.0, 0.228])          # the ball's middle (between the body and head joints)
R = np.array([0.198, 0.182, 0.17])       # its radii (picture: 440 px wide, 380 tall at 0.00087 a pixel)
THICK = 0.0135                           # a root's radius
HOLLOW_SPEC = (0.0, math.radians(13), math.radians(33), math.radians(17))
EYE_X, EYE_Z, EYE_HALF = 0.05, 0.264, (0.022, 0.024)


def sph(az, el, lift=0.0, c=C, r=R):
    """A point over a ball at an angle round from the front (radians, + toward +X) and up, lifted by a share."""
    d = np.array([math.sin(az) * math.cos(el), -math.cos(az) * math.cos(el), math.sin(el)])
    return np.array(c) + d * np.array(r) * (1 + lift)


def ball(k, name, c, r, color, bone, hollow, depth=0.13, deform=None, sub=5):
    """The peat under the roots, a shallow dimple pressed into its front where the hollow is."""
    az0, el0, hw, hh = hollow
    def dimple(V):
        V = V.copy() if deform is None else deform(V.copy())
        az = np.arctan2(V[:, 0], -V[:, 1])
        el = np.arcsin(np.clip(V[:, 2] / np.maximum(np.linalg.norm(V, axis=1), 1e-6), -1, 1))
        q = ((az - az0) / (hw * 1.05)) ** 2 + ((el - el0) / (hh * 1.1)) ** 2
        return V * (1 - depth * np.exp(-q ** 2))[:, None]
    k.add(name, ell(c, r, deform=dimple, sub=sub), color, bone)


def hollow_paint(k, c, r, hollow, color, on):
    """The hollow's dark over the dimple, its ragged edge hidden by the roots round it."""
    az0, el0, hw, hh = hollow
    c, r = np.array(c), np.array(r)
    def mask(P):
        d = (P - c) / r
        az = np.arctan2(d[:, 0], -d[:, 1])
        el = np.arcsin(np.clip(d[:, 2] / np.maximum(np.linalg.norm(d, axis=1), 1e-6), -1, 1))
        a = np.arctan2(el - el0, az - az0)
        rr = 1.15 + 0.05 * np.sin(5 * a) + 0.03 * np.sin(3 * a + 1)
        q = np.sqrt(((az - az0) / hw) ** 2 + ((el - el0) / (hh * 1.1)) ** 2) - rr
        return inside(q, 0.05) * (d[:, 1] < 0)
    k.paint(mask, color, on=on)


def vine(k, name, pts, radius, color, bone, seg=10, per=5):
    """One root, loose so that it keeps its own round edge against the ball and its fellows."""
    pts = np.array(pts, float)
    rad = radius if np.ndim(radius) else [radius] * len(pts)
    k.add(name, tube(pts, rad, seg=seg, per=per), color, bone, fuse=False, surface="leather")


def in_hollow(d, hollow, margin=1.2):
    az0, el0, hw, hh = hollow
    az = math.atan2(d[0], -d[1]); el = math.asin(max(-1, min(1, d[2])))
    return ((az - az0) / (hw * margin)) ** 2 + ((el - el0) / (hh * margin)) ** 2 < 1


def arcs(k, prefix, count, seed, c, r, radius, colours, bone_of, hollow, span=(0.45, 0.85), lift=(0.05, 0.16),
         lowest=-0.8, highest=0.62, hoops=0.15, flat=1.0, seg=10):
    """
    Roots wound over a ball: arcs round its surface spread by the golden angle, each rising off it toward its middle,
    a share in tall hoops; none crosses the hollow, none under `lowest` or over `highest` (the moss and reeds there).
    flat squashes the ball's upright share of each arc (a raft's sides).
    """
    rs = np.random.RandomState(seed)
    c, r = np.array(c, float), np.array(r, float)
    made = 0
    for i in range(count):
        y = 1 - 2 * (i + 0.5) / count
        ring = math.sqrt(max(0.0, 1 - y * y))
        a = i * 2.39996 + rs.rand() * 0.6
        n = np.array([math.sin(a) * ring, -math.cos(a) * ring, y])
        if y < lowest or y > highest:
            continue
        t = np.cross(n, (0, 0, 1.0) if abs(n[2]) < 0.95 else (1.0, 0, 0)); t /= np.linalg.norm(t)
        turn = (rs.rand() - 0.5) * math.pi * flat
        u = t * math.cos(turn) + np.cross(n, t) * math.sin(turn)
        sp = span[0] + (span[1] - span[0]) * rs.rand()
        lf = lift[0] + (lift[1] - lift[0]) * rs.rand()
        if rs.rand() < hoops:
            lf *= 2.0
        pts, bad = [], False
        for s in np.linspace(-1, 1, 7):
            d = n * math.cos(s * sp) + u * math.sin(s * sp); d /= np.linalg.norm(d)
            if in_hollow(d, hollow) or d[2] < lowest - 0.05 or d[2] > highest + 0.08:
                bad = True; break
            pts.append(c + d * r * (1 + radius / r.min() * 0.6 + lf * math.cos(s * math.pi / 2) ** 1.5))
        if bad:
            continue
        vine(k, f"{prefix}{made}", pts, radius * (0.9 + 0.2 * rs.rand()), colours[made % len(colours)], bone_of(pts[3]), seg=seg)
        made += 1
    return made


def dangle(k, prefix, count, seed, c, r, radius, colours, bone, floor, length=(0.05, 0.09), within=0.8):
    """Loose root ends hanging under the mat, each wavering down and out to a point no lower than the floor."""
    rs = np.random.RandomState(seed)
    c, r = np.array(c, float), np.array(r, float)
    for i in range(count):
        a = i * 2.39996 + rs.rand() * 0.5
        rad = within * math.sqrt((i + 0.5) / count)
        base = c + np.array([math.sin(a) * rad * r[0], -math.cos(a) * rad * r[1], 0.0])
        base[2] = c[2] - r[2] * math.sqrt(max(0.05, 1 - rad * rad)) + radius * 0.5
        out = np.array([math.sin(a), -math.cos(a), 0.0])
        L = length[0] + (length[1] - length[0]) * rs.rand()
        L = min(L, base[2] - floor - radius)
        pts = []
        for j in range(5):
            t = j / 4
            wav = math.sin(t * math.pi * 1.5 + i) * 0.25 * L
            pts.append(base + out * (0.45 * L * t + wav * t) + np.array([0, 0, -L * t]))
        vine(k, f"{prefix}{i}", pts, [radius, radius * 0.95, radius * 0.9, radius * 0.85, radius * 0.8],
             colours[i % len(colours)], bone, seg=8, per=4)


def ell_along(c, r, n, sub=3):
    """An ellipsoid whose third radius lies along n (a pad of moss on a surface)."""
    a, b = axes(n)
    n = np.array(n, float); n /= np.linalg.norm(n)
    V, F = ell((0, 0, 0), r, sub=sub)
    return V @ np.stack([a, b, n], axis=1).T + np.array(c, float), F


def moss(k, prefix, places, color, bone_of):
    """Pads of moss fused on the peat between the roots: (point, normal, radius) each."""
    for i, (p, n, rr) in enumerate(places):
        k.add(f"{prefix}{i}", ell_along(p, (rr, rr * 0.85, rr * 0.36), n), color, bone_of(p))


def flat_blade(pts, radii, axis, f, seg=10, per=6):
    """The kit's blade (a tube squashed about its own line along axis by f) at fewer points round and along it: a
    reed or a frond, many of them to a model."""
    V, F = tube(pts, radii, seg=seg, per=per)
    a = np.array(axis, float); a /= np.linalg.norm(a)
    p = np.array(pts, float)
    line = np.vstack([p[i] + (p[i + 1] - p[i]) * t for i in range(len(p) - 1) for t in np.linspace(0, 1, 40)])
    near = line[np.argmin(((V[:, None, :] - line[None]) ** 2).sum(2), axis=1)]
    d = (V - near) @ a
    return V - np.outer(d * (1 - f), a), F


def reed(k, name, base, az, tilt, length, width, color, bone, droop=0.25, f=0.55):
    """A reed blade: a flat tapered blade from base up and out at an angle round (az, + toward +X from the front)
    and a tilt from the upright, arching over toward its tip; its face turned outward."""
    out = np.array([math.sin(az), -math.cos(az), 0.0])
    d0 = unit(*(out * math.sin(tilt) + np.array([0, 0, math.cos(tilt)])))
    pts = []
    for j in range(5):
        t = j / 4
        pts.append(np.array(base) + d0 * length * t + out * length * droop * t * t
                   - np.array([0, 0, length * droop * 0.7 * t ** 3]))
    side = np.cross(d0, (0, 0, 1.0)) if abs(d0[2]) < 0.999 else np.array([1.0, 0, 0])
    side /= np.linalg.norm(side)
    face = np.cross(side, d0)
    radii = [width, width * 0.95, width * 0.75, width * 0.45, width * 0.12]
    k.add(name, flat_blade(pts, radii, face, f), color, bone, fuse=False, surface="leaf")
    return pts


def cattail(k, name, base, az, tilt, length, bone, head=(0.017, 0.042), stalk=0.0105):
    """A cattail: a stalk standing up and out, a long brown head near its top and a short spike over it."""
    out = np.array([math.sin(az), -math.cos(az), 0.0])
    d = unit(*(out * math.sin(tilt) + np.array([0, 0, math.cos(tilt)])))
    b = np.array(base, float)
    top = b + d * length
    k.add(name + "stalk", tube([b, b + d * length * 0.5, top], [stalk, stalk, stalk * 0.9], seg=10), STALK, bone,
          fuse=False, surface="leaf")
    hc = top - d * head[1] * 0.9
    # an ellipsoid along the stalk, its long radius on d
    k.add(name + "head", ell_along(hc, (head[0], head[0], head[1]), d), CAT, bone, fuse=False, surface="fur")
    tip = top + d * head[1] * 0.25
    k.add(name + "spike", tube([top - d * 0.004, tip, tip + d * head[1] * 0.4], [stalk * 0.85, stalk * 0.75, stalk * 0.6],
                               seg=8), STALK, bone, fuse=False, surface="leaf")


def tuft(k, prefix, centre, spread, count, seed, lengths, width, lean, bone, colours=(REED, REED2, REED3),
         tilts=(0.12, 0.75), droop=(0.12, 0.4)):
    """A tuft of reed blades from a patch round centre, fanned all round and leaning toward `lean` (a direction)."""
    rs = np.random.RandomState(seed)
    lean = np.array(lean, float)
    made = []
    for i in range(count):
        a = i * 2.39996 + rs.rand() * 0.5
        rad = spread * math.sqrt((i + 0.5) / count)
        base = np.array(centre, float) + np.array([math.sin(a) * rad, -math.cos(a) * rad, 0.0])
        t = tilts[0] + (tilts[1] - tilts[0]) * (rad / spread) + rs.rand() * 0.12
        # a blade leans more where it faces the way the tuft leans
        face = np.array([math.sin(a), -math.cos(a)])
        t += 0.25 * max(0.0, float(face @ lean[:2]))
        L = lengths[0] + (lengths[1] - lengths[0]) * rs.rand()
        dr = droop[0] + (droop[1] - droop[0]) * rs.rand()
        made.append(reed(k, f"{prefix}{i}", base, a, t, L, width * (0.85 + 0.3 * rs.rand()), colours[i % len(colours)],
                         bone, droop=dr))
    return made


def teal_eye(u, v):
    """A glowing teal eye: a darker shade low in it and a white glint up and toward the nose."""
    c = np.tile(srgb(TEAL), (len(u), 1))
    c[(u / 0.9) ** 2 + ((v + 0.75) / 0.55) ** 2 < 1] = srgb(TEALDK)
    c[((u + 0.25) / 0.3) ** 2 + ((v - 0.3) / 0.3) ** 2 < 1] = srgb(GLINT)
    return c


def lay_eyes(k, state, centres, normals, half, lid, ink, brow=None, eps=0.003):
    """The two eyes; u outward on both. brow: the top line's slope toward the nose (a glower), or None."""
    for s in (1, -1):
        c = centres(s); n = normals(s)
        look = eye_look(state, teal_eye, lid, ink, line=0.16)
        if brow is not None and state in ("Open", "Fierce"):
            def cut(u, v, f=look, b=brow):
                col = f(u, v)
                col[v > 0.55 + b * u] = lid
                return col
            look = cut
        col = look if s > 0 else (lambda u, v, f=look: f(-u, v))
        k.decal(c, n, half, col, eps=eps, rings=20, segs=56)


def board(tag):
    """The game's board check on everything built: the four-corner sum against the square it frames."""
    V = np.vstack([np.array([v.co[:] for v in o.data.vertices]) for o in bpy.data.objects
                   if o.type == "MESH" and not o.name.startswith("eyes.")])
    w, l, h = np.ptp(V[:, 0]), np.ptp(V[:, 1]), V[:, 2].max()
    sq = 1.3 * max(h, 0.85 * max(w, l)); sm = 0.853 * w + 0.522 * l
    t = math.radians(31.5); span = max(np.ptp(V[:, 0] * math.cos(t) + V[:, 1] * math.sin(t)), np.ptp(V[:, 0] * math.cos(t) - V[:, 1] * math.sin(t)))
    print(f"KIT: board {tag}: width {w:.3f} length {l:.3f} height {h:.3f} lowest {V[:, 2].min():.3f}; "
          f"four-corner sum {sm:.3f} of square {sq:.3f} ({sm / sq:.2f}); seen at 31.5 degrees {span:.3f} ({span / sq:.2f})")


def bone_of(p):
    return "head" if p[2] > C[2] + 0.06 else "body"


def plaurel(src, out):
    k = Kit(src, coat="leather")
    # ---- the peat ball, its hollow, the moss cap on top ----------------------------------------------------------
    ball(k, "core", C, R, CORE, "body", HOLLOW_SPEC)
    # the moss under the reeds, a low ragged mound sunk into the ball's top, not a rim
    k.add("cap", ell((0.0, 0.01, C[2] + R[2] * 0.8), (0.1, 0.095, 0.045), deform=lumpy(5, 3, 0.18)), MOSS, "head",
          surface="leaf")
    hollow_paint(k, C, R, HOLLOW_SPEC, HOLLOW, on=["core"])
    rs = np.random.RandomState(7)
    places = []
    for i in range(16):
        az = i * 2.39996 + rs.rand() * 0.4
        el = math.radians(-35 + 75 * rs.rand())
        d = np.array([math.sin(az) * math.cos(el), -math.cos(az) * math.cos(el), math.sin(el)])
        if in_hollow(d, HOLLOW_SPEC, 1.5):
            continue
        p = C + d * R * 1.0
        n = (p - C) / R ** 2
        places.append((p, n / np.linalg.norm(n), 0.03 + 0.02 * rs.rand()))
    moss(k, "moss", places, MOSS2, bone_of)

    # ---- the roots wound all over it, a brow of roots over the hollow, the fringe hanging under it ------------------
    arcs(k, "root", 100, 123, C, R, THICK, (ROOT, ROOT2, ROOT3, ROOT, MOSSROOT, ROOT3), bone_of, HOLLOW_SPEC, highest=0.78)
    D = math.radians
    vine(k, "brow", [sph(D(a), D(e), l) for a, e, l in
                     ((-52, 8, 0.05), (-40, 28, 0.1), (-20, 34, 0.13), (0, 30, 0.14), (20, 35, 0.13), (40, 27, 0.1),
                      (52, 8, 0.05))], THICK * 1.15, ROOT2, "head")
    vine(k, "under", [sph(D(a), D(e), l) for a, e, l in
                      ((-50, 2, 0.04), (-30, -6, 0.1), (-10, -2, 0.12), (10, -6, 0.12), (30, -2, 0.1), (50, 4, 0.04))],
         THICK, ROOT, "body")
    for s in (1, -1):
        vine(k, f"cheek{'R' if s > 0 else 'L'}", [sph(D(a * s), D(e), l) for a, e, l in
                                                  ((30, 40, 0.03), (42, 22, 0.1), (40, 6, 0.12), (44, -10, 0.1),
                                                   (54, -24, 0.04))], THICK, ROOT3 if s > 0 else ROOT, "body")
    dangle(k, "hang", 16, 124, C, R, THICK * 0.95, (ROOT, ROOT3, ROOT2), "body", floor=0.004)

    # ---- the reeds: a tall tuft out of the top, leaning a little toward +X, five cattails among them --------------
    top = np.array([0.0, 0.01, C[2] + R[2] * 0.98])
    tuft(k, "reed", top, 0.095, 26, 9, (0.25, 0.34), 0.017, (0.55, 0.1), "head", tilts=(0.06, 0.6), droop=(0.08, 0.36))
    for i, (az, tilt, L) in enumerate(((-0.9, 0.45, 0.29), (0.4, 0.22, 0.31), (1.4, 0.55, 0.3), (2.6, 0.4, 0.29),
                                       (-2.3, 0.42, 0.28))):
        b = top + np.array([math.sin(az) * 0.05, -math.cos(az) * 0.05, -0.005])
        cattail(k, f"cat{i}", b, az, tilt, L, "head")      # not on `sprout`, whose joint stands over their tops

    k.build(voxel=0.006, smooth=3, band=0.008)
    board("Plaurel")

    # ---- the eyes: two glowing teal ovals deep in the hollow, cast from the front ----------------------------------
    def eyes(state):
        lay_eyes(k, state, lambda s: np.array([EYE_X * s, -0.16, EYE_Z]), lambda s: unit(0.16 * s, -1.0, 0.08),
                 EYE_HALF, srgb(HOLLOW), srgb(TEALDK), brow=None)
    k.eye_states(eyes)
    k.export(out)


if __name__ == "__main__":
    plaurel(*args())
