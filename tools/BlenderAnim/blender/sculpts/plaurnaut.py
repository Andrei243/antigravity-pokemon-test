# Plaurnaut (Carpathia No. 10124) sculpted from nothing on the skeleton and clips of the game's own export of it:
#   blender --background --factory-startup --python sculpts/plaurnaut.py -- <the export's Plaurnaut.glb> <out.glb>
#
# From its picture (docs/art/reference/gemini/carpathia/10124-Plaurnaut.jpg) and its brief (CP-dex-3, No. 124): the
# grown Plaurel, a floating island of the delta (a plaur): a broad oval raft of peat and tangled roots, flat on top
# and rounded under, a fringe of roots hanging from its underside; at its bow a broad gentle face grown out of the root
# mass, heavy mossy brows, the line's glowing teal eyes in dark hollows, a broad nose and a wide calm smile; on its back
# moss, a little pond with lily pads and two water lilies, clumps of reeds with cattails, a willow sapling with a
# drooping crown at the stern, two small birds. The export is a body generated by rule: only its skeleton and clips are
# used; it hovers (the export's lowest, 0.08) as the island floats, with the hanging roots reaching down to it.
#
# Grown from plaurel.py (`sibling`): its roots, moss, reeds, cattails, eyes and board check, its palette.
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np
from sculptkit import Kit, ell, tube, blade, srgb, inside, unit, lumpy, sibling, args

pl = sibling("plaurel")

FACE, POND, PAD, LILY, LILYCORE = "#6E5A3C", "#6A8A98", "#4E8A3C", "#F2B6C8", "#F4D24A"
WILLOW, WILLOW2, BARK = "#A6C454", "#88AA3E", "#5E4A34"
BLUEBIRD, ORANGEBIRD, BEAK = "#6AA6E0", "#F08A3A", "#E8B030"

C = np.array([0.0, 0.03, 0.318])            # the raft's middle
R = np.array([0.24, 0.315, 0.14])           # its radii: long along the body, the bow (the face) at -Y
TOP = C[2] + R[2] * 0.93                    # the flat top
FACE_SPEC = (0.0, math.radians(8), math.radians(40), math.radians(40))   # kept clear of roots round the face
EYE_X, EYE_Z, EYE_HALF = 0.078, 0.356, (0.03, 0.032)


def raft(V):
    """The unit sphere as a raft: its top flattened, a little fuller at the shoulders, the underside rounded."""
    V = V.copy()
    V[:, 2] = np.where(V[:, 2] > 0.55, 0.55 + (V[:, 2] - 0.55) * 0.25, V[:, 2])
    V[:, :2] *= (1 + 0.08 * np.clip(V[:, 2] + 0.2, 0, 1))[:, None]
    return V


def bone_of(p):
    return "head" if p[2] > C[2] + 0.04 else "body"


def plaurnaut(src, out):
    k = Kit(src, coat="leather")
    # ---- the raft, the moss on its back, the pond --------------------------------------------------------------
    k.add("core", ell(C, R, deform=raft, sub=5), pl.CORE, "body")
    k.add("cap", ell((0.0, 0.03, TOP - 0.012), (0.2, 0.27, 0.03), deform=lumpy(7, 3, 0.08)), pl.MOSS, "head",
          surface="leaf")
    k.paint(lambda P: inside(np.hypot((P[:, 0] - 0.02) / 0.115, (P[:, 1] + 0.04) / 0.13) - 1, 0.05)
            * inside(TOP - 0.03 - P[:, 2], 0.004), POND, on=["cap"])
    # ---- the face at the bow: a broad brown front, cheeks, a nose, heavy mossy brows ----------------------------
    k.add("face", ell((0.0, -0.25, 0.33), (0.17, 0.09, 0.1)), FACE, "head")
    k.add("cheek", ell((0.1, -0.28, 0.3), (0.06, 0.05, 0.05)), FACE, "head", mirror=True)
    k.add("nose", ell((0.0, -0.342, 0.31), (0.048, 0.04, 0.036)), FACE, "head")
    k.add("brow", ell((0.082, -0.32, 0.397), (0.064, 0.03, 0.02), rot=(0, 14, -10)), pl.MOSS, "head", mirror=True,
          surface="leaf")
    # dark hollows round the eyes (patches under the eyes' own, in every state: paint was ragged at this voxel)
    for s in (1, -1):
        k.decal((EYE_X * s, -0.31, EYE_Z), pl.unit(0.28 * s, -1.0, 0.05), (0.043, 0.041), pl.HOLLOW, eps=0.0016,
                rings=12, segs=40)
    # the wide calm smile: a curved dark band under the nose on a patch of the face's own colour
    fc, dk = srgb(FACE), srgb(pl.HOLLOW)
    def smile(u, v):
        c = np.tile(fc, (len(u), 1))
        c[(np.abs(v - (-0.35 + 0.95 * u * u)) < 0.2) & (np.abs(u) < 0.92)] = dk
        return c
    k.decal((0.0, -0.312, 0.262), (0.0, -1.0, -0.12), (0.115, 0.04), smile, eps=0.0018, rings=16, segs=64)

    # ---- the roots wound round its sides, a fringe hanging under it, moss pads among them ----------------------------
    pl.arcs(k, "root", 84, 124, C, R, 0.016, (pl.ROOT, pl.ROOT2, pl.ROOT3), bone_of, FACE_SPEC, span=(0.35, 0.7),
            lift=(0.04, 0.12), lowest=-0.85, highest=0.5, hoops=0.08, flat=0.5, seg=8)
    D = math.radians
    for s in (1, -1):
        sd = "R" if s > 0 else "L"
        # roots framing the face, from over the brows down past the cheeks
        pl.vine(k, f"frame{sd}", [pl.sph(D(a * s), D(e), l, C, R) for a, e, l in
                                  ((8, 52, 0.06), (30, 46, 0.1), (46, 24, 0.1), (50, 0, 0.1), (46, -28, 0.08),
                                   (36, -50, 0.04))], 0.017, pl.ROOT2 if s > 0 else pl.ROOT, "head")
        pl.vine(k, f"jaw{sd}", [pl.sph(D(a * s), D(e), l, C, R) for a, e, l in
                                ((4, -46, 0.08), (18, -38, 0.12), (32, -40, 0.1), (44, -46, 0.06))],
                0.016, pl.ROOT3, "body")
    pl.dangle(k, "hang", 22, 125, C, R, 0.0155, (pl.ROOT, pl.ROOT3, pl.ROOT2), "body", floor=0.08,
              length=(0.07, 0.11), within=0.85)
    rs = np.random.RandomState(24)
    places = []
    for i in range(22):
        az = i * 2.39996 + rs.rand() * 0.4
        el = math.radians(-30 + 55 * rs.rand())
        d = np.array([math.sin(az) * math.cos(el), -math.cos(az) * math.cos(el), math.sin(el)])
        if pl.in_hollow(d, FACE_SPEC, 1.2):
            continue
        p = C + d * R
        n = (p - C) / R ** 2
        places.append((p, n / np.linalg.norm(n), 0.035 + 0.025 * rs.rand()))
    pl.moss(k, "moss", places, pl.MOSS2, bone_of)

    # ---- on its back: lily pads and lilies on the pond -------------------------------------------------------------
    for i, (x, y, r) in enumerate(((-0.03, -0.09, 0.03), (0.07, -0.06, 0.026), (0.0, 0.03, 0.028), (0.08, 0.02, 0.022),
                                   (-0.06, -0.01, 0.024))):
        k.add(f"pad{i}", ell((x, y, TOP + 0.02), (r, r * 0.95, 0.006), sub=3), PAD, "head", fuse=False, surface="leaf")
    for i, (x, y) in enumerate(((0.07, -0.06), (-0.06, -0.01))):
        base = np.array([x, y, TOP + 0.026])
        for j in range(6):
            a = j * math.pi / 3
            d = np.array([math.cos(a), math.sin(a), 0.0])
            k.add(f"lily{i}p{j}", ell(base + d * 0.012 + (0, 0, 0.008), (0.014, 0.008, 0.006), rot=(0, -35, math.degrees(a))),
                  LILY, "head", fuse=False, surface="leaf")
        k.add(f"lily{i}c", ell(base + (0, 0, 0.012), (0.008, 0.008, 0.007), sub=2), LILYCORE, "head", fuse=False)

    # ---- reed clumps with cattails, round the pond ------------------------------------------------------------------
    clumps = [((-0.16, -0.19), 8, (0.12, 0.2)), ((-0.15, 0.15), 9, (0.14, 0.22)), ((0.17, -0.05), 9, (0.13, 0.21)),
              ((0.14, 0.23), 7, (0.12, 0.19)), ((-0.04, 0.25), 6, (0.1, 0.16))]
    for i, ((x, y), n, lens) in enumerate(clumps):
        pl.tuft(k, f"reed{i}_", (x, y, TOP - 0.01), 0.045, n, 30 + i, lens, 0.014, (x, y * 0.5), "head",
                tilts=(0.05, 0.45), droop=(0.08, 0.3))
    for i, (x, y, az, tilt, L) in enumerate(((-0.17, -0.17, -1.6, 0.25, 0.17), (-0.13, 0.16, -1.2, 0.18, 0.18),
                                             (0.18, -0.07, 1.5, 0.22, 0.17), (0.15, 0.22, 1.9, 0.2, 0.15),
                                             (-0.18, 0.1, -2.0, 0.3, 0.16), (0.2, 0.02, 1.1, 0.3, 0.16))):
        pl.cattail(k, f"cat{i}", (x, y, TOP - 0.01), az, tilt, L, "head", head=(0.015, 0.036), stalk=0.0105)

    # ---- the willow sapling at the stern: a forked trunk, a drooping crown of fronds -----------------------------------
    W = np.array([0.05, 0.2, TOP - 0.01])
    k.add("trunk", tube([W, W + (0.004, 0.004, 0.08), W + (0.0, 0.01, 0.16)], [0.024, 0.019, 0.015], seg=12), BARK,
          "head", fuse=False, surface="leather")
    for s in (1, -1):
        k.add(f"branch{'R' if s > 0 else 'L'}", tube([W + (0.0, 0.006, 0.11), W + (0.04 * s, 0.0, 0.17),
                                                     W + (0.07 * s, -0.01, 0.21)], [0.014, 0.012, 0.011], seg=10),
              BARK, "head", fuse=False, surface="leather")
    CR = W + np.array([0.0, 0.0, 0.22])
    # the crown: four drooping clusters (the picture's weeping umbrellas), each a low dome with a curtain of fronds
    # hanging from its rim, arching out and then down
    n = 0
    for i, (dx, dy, dz, col, col2) in enumerate(((0.0, 0.0, 0.035, WILLOW, WILLOW2), (-0.075, 0.005, -0.015, WILLOW2, WILLOW),
                                                 (0.078, -0.01, -0.01, WILLOW, WILLOW2), (0.0, 0.065, -0.005, WILLOW2, WILLOW))):
        lc = CR + np.array([dx, dy, dz])
        k.add(f"crown{i}", ell(lc, (0.062, 0.056, 0.034), deform=lumpy(5, 3, 0.12), sub=3), col, "head",
              fuse=False, surface="leaf")
        for j in range(7):
            a = j * 2 * math.pi / 7 + 0.4 * i
            outd = np.array([math.cos(a), math.sin(a), 0.0])
            rim = lc + outd * 0.05 - (0, 0, 0.012)
            L = 0.085 + 0.03 * ((j * 3 + i) % 4) / 3
            pts = [rim, rim + outd * 0.02 - (0, 0, L * 0.35), rim + outd * 0.026 - (0, 0, L * 0.72),
                   rim + outd * 0.022 - (0, 0, L)]
            k.add(f"frond{n}", pl.flat_blade(pts, [0.017, 0.016, 0.012, 0.004], outd, 0.42), col2 if j % 2 else col, "head",
                  fuse=False, surface="leaf")
            n += 1

    # ---- two small birds: one on the rim at the bow, one in the willow ----------------------------------------------
    def bird(name, p, colour, facing, bone):
        p = np.array(p, float); f = unit(*facing)
        k.add(name + "body", ell(p, (0.019, 0.019, 0.017)), colour, bone, fuse=False)
        hd = p + f * 0.017 + (0, 0, 0.016)
        k.add(name + "head", ell(hd, (0.0135, 0.0135, 0.0135), sub=3), colour, bone, fuse=False)
        k.add(name + "beak", tube([hd + f * 0.01, hd + f * 0.022], [0.006, 0.002], seg=8), BEAK, bone, fuse=False)
        k.add(name + "tail", tube([p - f * 0.012, p - f * 0.034 + (0, 0, 0.008)], [0.009, 0.006], seg=8), colour, bone,
              fuse=False)
    bird("bird0", (-0.15, -0.21, TOP + 0.004), BLUEBIRD, (0.3, -1.0, 0.0), "head")
    bird("bird1", (0.11, 0.2, CR[2] - 0.05), ORANGEBIRD, (0.6, -0.8, 0.0), "head")

    k.build(voxel=0.0095, smooth=3, band=0.01)
    pl.board("Plaurnaut")

    # ---- the eyes: the line's glowing teal ovals in their dark hollows under the brows ---------------------------------
    def eyes(state):
        pl.lay_eyes(k, state, lambda s: np.array([EYE_X * s, -0.31, EYE_Z]), lambda s: pl.unit(0.28 * s, -1.0, 0.05),
                    EYE_HALF, srgb(pl.HOLLOW), srgb(pl.TEALDK))
    k.eye_states(eyes)
    k.export(out)


if __name__ == "__main__":
    plaurnaut(*args())
