# Tantaroi (Carpathia No. 10126) sculpted from nothing on the skeleton and clips of the game's own export of it:
#   blender --background --factory-startup --python sculpts/tantaroi.py -- <the export's Tantaroi.glb> <out.glb>
#
# From its picture (docs/art/reference/gemini/carpathia/10126-Tantaroi.jpg) and its brief (CP-dex-3, No. 126): the
# grown Tantarel, a swarm of small mosquitoes that together take the shape of one big mosquito: the same great
# yellow-green eyes under a fiercer brow, the feathery antennae, the long proboscis, the banded body (its abdomen
# fuller, grey and green), six long banded legs, the clear wings tinted violet with a violet glow at their rims (the
# swarm's hazy violet outline); its whole body crawling with small dark mosquitoes, their pale wings up, and a few
# stragglers buzzing close round it. The export is a body generated by rule: only its skeleton and clips are used.
#
# Grown from tantarel.py (`sibling`): its body, wings, legs, proboscis, antennae and eyes, with a look of its own and
# the swarm laid over the body as loose pieces.
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np
from sculptkit import ell, tube, unit, axes, sibling, args

ta = sibling("tantarel")

MINI, MINIWING = "#26262C", "#5E5A6A"
HAZE = "#8E4CF0"

LOOK = dict(ta.LOOK)
LOOK.update(
    brow=0.52,                                       # a fiercer glower
    abdomen=np.array([0.0, 0.225, 0.355]), abdomen_r=np.array([0.126, 0.185, 0.124]),
    bands=(ta.GREYDK, ta.GREY, ta.GREEN, ta.GREYDK, ta.VIOLET, ta.GREYDK, ta.GREEN, ta.GREYDK, ta.GREEN),
    wing_len=0.37, wing_w=0.1, hind_len=0.285, hind_w=0.075,
    wing_fill="#E0D4F6", wing_rim=HAZE, wing_glow=None, rim_glow=HAZE,
    leg_r=0.0135, proboscis_r=0.014,
)


def mini(k, name, p, n, heading, size, bone):
    """One small mosquito at p, its back to n, facing `heading`: a dark head, thorax and pointed abdomen in a line,
    two short dark legs trailing, two small smoke-grey wings no longer than the body laid back over it. Built in its
    own frame (side, n, h), which is right-handed."""
    p, n = np.array(p, float), unit(*n)
    h = np.array(heading, float); h = h - n * (h @ n); h = h / np.linalg.norm(h)
    side = np.cross(n, h)
    M = np.stack([side, n, h], 1)
    c = p + n * size * 0.32

    def put(V):
        return V @ M.T + c

    def taper(V):
        V = V.copy()
        t = np.clip((1 - V[:, 2]) / 2, 0, 1)            # 0 at the front of the abdomen, 1 at its point
        V[:, :2] *= (1 - 0.75 * t ** 1.5)[:, None]
        return V
    V, F = ell((0, 0, 0), (size * 0.3, size * 0.3, size * 0.34), sub=2)
    k.add(name + "t", (put(V), F), MINI, bone, fuse=False)                       # thorax
    V, F = ell((0, 0, size * 0.5), (size * 0.24,) * 3, sub=2)
    k.add(name + "h", (put(V), F), MINI, bone, fuse=False)                       # head
    V, F = ell((0, 0, -size * 0.85), (size * 0.25, size * 0.25, size * 0.6), deform=taper, sub=2)
    k.add(name + "a", (put(V), F), MINI, bone, fuse=False)                       # abdomen
    r = max(0.011, size * 0.13)
    for s in (1, -1):
        pts = np.array([(s * size * 0.12, -size * 0.18, -size * 0.05), (s * size * 0.3, -size * 0.3, -size * 0.55),
                        (s * size * 0.34, -size * 0.32, -size * 1.0)])
        k.add(name + ("lR" if s > 0 else "lL"), (put(tube(pts, [r, r, r * 0.9], seg=8, per=4)[0]),
                                                tube(pts, [r, r, r * 0.9], seg=8, per=4)[1]), MINI, bone, fuse=False)
        V, F = ell((s * size * 0.26, size * 0.26, -size * 0.55), (size * 0.2, size * 0.075, size * 0.62),
                   rot=(12, 0, -18 * s), sub=2)
        k.add(name + ("wR" if s > 0 else "wL"), (put(V), F), MINIWING, bone, fuse=False)


def swarm(k, L):
    """The swarm: small mosquitoes all over the thorax, the abdomen and the crown and back of the head, never on the
    face, and a few stragglers close round the body."""
    rs = np.random.RandomState(126)
    ax = ta.abdomen_axis(L)
    bodies = [("thorax", L["thorax"], L["thorax_r"], 6, "body"), ("abdomen", L["abdomen"], L["abdomen_r"], 11, "body"),
              ("head", L["head"], L["head_r"], 8, "head")]
    made = 0
    for nm, c, r, count, bone in bodies:
        for i in range(count):
            y = 1 - 2 * (i + 0.5) / count
            ring = math.sqrt(max(0.0, 1 - y * y))
            a = i * 2.39996 + rs.rand() * 0.5
            d = np.array([math.cos(a) * ring, y, math.sin(a) * ring])
            if nm == "head" and (d[1] < 0.2 or d[2] < 0.05):
                continue                                # only the back of the head: the face and the eyes stay clear
            if d[2] < -0.75:
                continue                                # nor under the belly where the legs root
            if nm == "abdomen":
                t = math.radians(L["abdomen_tilt"])
                # into the abdomen's tilted frame
                d = np.array([d[0], d[1] * math.cos(t) - d[2] * math.sin(t), d[1] * math.sin(t) + d[2] * math.cos(t)])
            p = np.array(c) + d * np.array(r) * 0.98
            n = (p - c) / np.array(r) ** 2
            heading = np.array([rs.rand() - 0.5, rs.rand() - 0.5, rs.rand() - 0.5])
            mini(k, f"mini{made}", p, n, heading, 0.075 + 0.012 * rs.rand(), bone)
            made += 1
    # stragglers: hovering close round the body, on its bone, the nearest toward +X
    strays = (((0.19, 0.06, 0.5), (0.2, -1, 0.1)), ((0.18, 0.28, 0.42), (-0.2, -1, 0.15)),
              ((0.17, -0.06, 0.31), (0.4, -1, 0)), ((-0.2, 0.12, 0.52), (-0.3, -1, 0.1)), ((-0.17, 0.33, 0.33), (0.2, -1, 0)))
    for i, (p, hd) in enumerate(strays):
        mini(k, f"stray{i}", p, (0, 0, 1), hd, 0.07, "body")
    haze(k, L)
    print("KIT: swarm", made, "small mosquitoes on the body and", len(strays), "stragglers")


def haze(k, L):
    """The swarm's violet outline as a surface: a thin glowing line along the abdomen's back, and one down the outer
    side of each leg (tantarel.py's leg lines, offset outward)."""
    A, R, t = L["abdomen"], L["abdomen_r"], math.radians(L["abdomen_tilt"])
    pts = []
    for s in np.linspace(-0.72, 0.84, 11):
        w = 1 - ((max(0.0, (s + 1) / 2 - 0.55)) / 0.45) ** 1.6 * 0.82 if (s + 1) / 2 > 0.55 else 1.0
        y, z = s * R[1], R[2] * math.sqrt(max(0.0, 1 - s * s)) * w - 0.003
        pts.append(A + np.array([0.0, y * math.cos(t) - z * math.sin(t), y * math.sin(t) + z * math.cos(t)]))
    k.add("hazeback", tube(pts, [0.0085] * len(pts), seg=10, per=5), HAZE, "body", fuse=False, glow=HAZE)
    r = L["leg_r"]
    LEGS = [("legF", "leg{s}", [(0.03, -0.05, 0.385), (0.1, -0.1, 0.36), (0.13, -0.15, 0.22), (0.14, -0.17, 0.085)]),
            ("legM", "hind{s}", [(0.035, -0.005, 0.375), (0.12, 0.0, 0.345), (0.15, 0.02, 0.2), (0.16, 0.035, 0.082)]),
            ("legB", "hind{s}", [(0.03, 0.04, 0.38), (0.1, 0.1, 0.35), (0.13, 0.19, 0.21), (0.13, 0.24, 0.085)])]
    for name, bone, P in LEGS:
        P = np.array(P[1:], float)
        P = P + np.array([r * 0.85, 0.0, 0.0])                  # out along the leg's outer side
        P[-1] = P[-1] + np.array([0.0, 0.0, 0.012])              # ending short of the foot
        k.add("haze" + name, tube(P, [0.0065, 0.0062, 0.0058], seg=8, per=5), HAZE, bone, fuse=False, mirror=True,
              glow=HAZE)


if __name__ == "__main__":
    ta.tantarel(*args(), L=LOOK, extras=swarm, tag="Tantaroi")
