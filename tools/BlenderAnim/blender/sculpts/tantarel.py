# Tantarel (Carpathia No. 10125) sculpted from nothing on the skeleton and clips of the game's own export of it:
#   blender --background --factory-startup --python sculpts/tantarel.py -- <the export's Tantarel.glb> <out.glb>
#
# From its picture (docs/art/reference/gemini/carpathia/10125-Tantarel.jpg) and its brief (CP-dex-3, No. 125): a
# mosquito. A round grey head with two great bulging yellow-green eyes, dark upright pupils, a heavy grey brow
# slanting down over them toward the middle (the "annoying" glower); two feathery dark antennae out of the crown; a long
# thin dark proboscis curving down and forward, its tip violet; a round grey thorax ringed with darker bands; a big
# pointed abdomen hanging back and a little down, banded dark grey, violet and pale green, a green glow at its tip;
# two clear wings with dark rims raised over the back (a smaller blurred pair behind them); six long thin dark legs
# banded pale, bent at the knee, hanging. The export is a body generated by rule: only its skeleton and clips are used.
# It hovers (the export's lowest, 0.076): the legs hang to it.
#
# Written to be grown from (Tantaroi, the swarm): everything is `tantarel(src, out, LOOK)` with a look dict, and its
# parts are functions taking the kit.
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np
import bpy
from sculptkit import Kit, ell, tube, slab, ring_band, srgb, inside, unit, eye_look, axes, args

GREY, GREYDK, GREYLT = "#6E7078", "#45474F", "#A2A4AC"
VIOLET, GREEN, GREENGLOW = "#8A5AB8", "#8CC890", "#6CF08A"
LEG, LEGBAND = "#34353C", "#C6C8CE"
WING, WINGRIM = "#E4E9F2", "#30303A"
EYE, EYELT, PUPIL, GLINT, EYERIM = "#C2DC52", "#E6F49A", "#1A1C14", "#FFFFFF", "#7E9A2E"
TIP = "#A464F0"

LOOK = dict(
    head=np.array([0.0, -0.168, 0.414]), head_r=np.array([0.088, 0.086, 0.084]),
    eye_x=0.05, eye_y=-0.214, eye_z=0.418, eye_r=np.array([0.046, 0.04, 0.048]), eye_half=(0.04, 0.043),
    brow=0.36,                               # the brow's slope toward the nose across the eye (a glower)
    thorax=np.array([0.0, -0.01, 0.44]), thorax_r=np.array([0.074, 0.084, 0.082]),
    abdomen=np.array([0.0, 0.215, 0.36]), abdomen_r=np.array([0.112, 0.17, 0.112]), abdomen_tilt=-18.0,
    bands=(GREYDK, GREY, VIOLET, GREYDK, VIOLET, GREYDK, GREEN, GREYDK, GREEN),
    wing_len=0.35, wing_w=0.092, wing_lift=38, wing_sweep=-36, hind_len=0.27, hind_w=0.07, hind_lift=24, hind_sweep=-60,
    wing_fill=WING, wing_rim=WINGRIM, wing_glow=None,
    proboscis_r=0.0135, leg_r=0.0125, coat="shell",
)


def ell_along(c, r, n, sub=3):
    """An ellipsoid whose third radius lies along n."""
    a, b = axes(n)
    n = np.array(n, float); n /= np.linalg.norm(n)
    V, F = ell((0, 0, 0), r, sub=sub)
    return V @ np.stack([a, b, n], axis=1).T + np.array(c, float), F


def abdomen_axis(L):
    t = math.radians(L["abdomen_tilt"])
    return np.array([0.0, math.cos(t), math.sin(t)])


def body(k, L):
    """Head, eye bulges, neck, thorax and abdomen: one fused grey body, banded by paint."""
    k.add("head", ell(L["head"], L["head_r"]), GREY, "head")
    k.add("eyeball", ell((L["eye_x"], L["eye_y"], L["eye_z"]), L["eye_r"], rot=(0, 0, -24)), EYERIM, "head", mirror=True)
    k.add("neck", ell((0, -0.09, 0.425), (0.05, 0.05, 0.05)), GREY, "body")
    k.add("thorax", ell(L["thorax"], L["thorax_r"]), GREY, "body")
    ax = abdomen_axis(L)
    def pointed(V):
        V = V.copy()
        t = np.clip((V[:, 1] + 1) / 2, 0, 1)                # 0 at the thorax end, 1 at the tip
        w = np.where(t > 0.55, 1 - ((t - 0.55) / 0.45) ** 1.6 * 0.82, 1.0)
        w *= np.where(t < 0.12, 0.8 + 0.2 * t / 0.12, 1.0)
        V[:, 0] *= w; V[:, 2] *= w
        return V
    k.add("abdomen", ell(L["abdomen"], L["abdomen_r"], rot=(L["abdomen_tilt"], 0, 0), deform=pointed, sub=5), GREY, "body")
    # the thorax's rings: three darker bands across it
    T = L["thorax"]
    def rings(P):
        q = P[:, 1] - T[1]
        m = np.zeros(len(P))
        for y0 in (-0.042, 0.0, 0.042):
            m = np.maximum(m, inside(np.abs(q - y0) - 0.011, 0.002))
        return m * inside(np.linalg.norm((P - T) / L["thorax_r"], axis=1) - 1.15, 0.01)
    k.paint(rings, GREYDK, on=["thorax"])
    # the abdomen's bands, along its own axis
    A = L["abdomen"]; hl = L["abdomen_r"][1]; bands = L["bands"]
    def band(i):
        def m(P):
            s = ((P - A) @ ax) / hl                         # -1 at the thorax end, 1 at the tip
            lo = -0.92 + 1.84 * i / len(bands); hi = -0.92 + 1.84 * (i + 1) / len(bands)
            return inside(lo - s, 0.003) * inside(s - hi, 0.003)
        return m
    for i, c in enumerate(bands):
        if c != GREY:
            k.paint(band(i), c, on=["abdomen"])
    # the tip's green glow, painted down its end
    k.paint(lambda P: inside(0.86 - ((P - A) @ ax) / hl, 0.01), GREENGLOW, on=["abdomen"])
    # the head's crown a shade darker, and the brow over each eye
    H = L["head"]
    k.paint(lambda P: inside(H[2] + 0.04 - P[:, 2], 0.01) * inside(P[:, 1] - (H[1] + 0.05), 0.02)
            * inside(np.linalg.norm((P - H) / L["head_r"], axis=1) - 1.2, 0.01), GREYDK, on=["head"])


def wing(k, name, root, bone, length, width, lift, sweep, fill, rim, glow=None, thick=0.006, rim_glow=None):
    """A clear wing on both sides: a dark rim plate and the pale membrane inside it, standing proud of it both ways;
    raised in a V by lift and swept back by sweep (degrees)."""
    for s, side in ((1, "R"), (-1, "L")):
        li, sw = math.radians(lift), math.radians(sweep)
        ex = np.array([s * math.cos(li) * math.cos(sw), -math.cos(li) * math.sin(sw), math.sin(li)])
        ez = np.array([0.0, 1.0, 0.0]) - ex * ex[1]
        ez /= np.linalg.norm(ez)
        t = np.linspace(0, 1, 26)
        half = width * np.sqrt(np.clip(1 - ((t - 0.55) / 0.55) ** 2, 0, 1)) * (0.45 + 0.55 * t) + 0.004
        a = 0.006 + t * length
        outline = np.vstack([np.stack([a, half], 1), np.stack([a, -half * 0.75], 1)[::-1]])
        inner = np.vstack([np.stack([a[1:-1], half[1:-1] - 0.007], 1),
                           np.stack([a[1:-1], -(half[1:-1] * 0.75 - 0.007)], 1)[::-1]])
        o = np.array(root, float) * (s, 1, 1)
        k.add(f"{name}{side}", slab(outline, o, ex, ez, thick), rim, bone.format(s=side), fuse=False, glow=rim_glow)
        k.add(f"{name}in{side}", slab(inner, o, ex, ez, thick * 1.6), fill, bone.format(s=side), fuse=False,
              glow=glow)
        # one vein down its middle
        vein = np.array([(0.02, 0.003), (length * 0.9, 0.003), (length * 0.9, -0.003), (0.02, -0.003)])
        k.add(f"{name}vein{side}", slab(vein, o, ex, ez, thick * 2.2), rim, bone.format(s=side), fuse=False)


def legs(k, L):
    """Six long thin dark legs, bent at the knee, hanging to the export's lowest, each banded pale twice."""
    r = L["leg_r"]
    LEGS = [("legF", "leg{s}", [(0.03, -0.05, 0.385), (0.1, -0.1, 0.36), (0.13, -0.15, 0.22), (0.14, -0.17, 0.085)]),
            ("legM", "hind{s}", [(0.035, -0.005, 0.375), (0.12, 0.0, 0.345), (0.15, 0.02, 0.2), (0.16, 0.035, 0.082)]),
            ("legB", "hind{s}", [(0.03, 0.04, 0.38), (0.1, 0.1, 0.35), (0.13, 0.19, 0.21), (0.13, 0.24, 0.085)])]
    for name, bone, pts in LEGS:
        pts = np.array(pts)
        radii = [r * 1.15, r * 1.05, r * 0.95, r * 0.88]
        k.add(name, tube(pts, radii, seg=12, per=6), LEG, bone, fuse=False, mirror=True, surface="shell")
        for j, (i, t) in enumerate(((1, 0.45), (2, 0.5))):
            c = pts[i] + (pts[i + 1] - pts[i]) * t
            ax = pts[i + 1] - pts[i]
            rr = radii[i] + (radii[i + 1] - radii[i]) * t
            k.add(f"{name}band{j}", ring_band(c, ax, rr + 0.002, np.linalg.norm(ax) * 0.22, thick=0.005), LEGBAND,
                  bone, fuse=False, mirror=True)


def proboscis(k, L):
    """The long thin proboscis, out from under the eyes, curving down and forward to a violet glowing tip."""
    r = L["proboscis_r"]
    pts = [(0.0, -0.228, 0.372), (0.0, -0.29, 0.33), (0.0, -0.35, 0.26), (0.0, -0.395, 0.18), (0.0, -0.418, 0.13)]
    k.add("proboscis", tube(pts, [r * 1.2, r, r * 0.92, r * 0.85, r * 0.8], seg=12, per=6), "#3C3D46", "head", fuse=False)
    tip = np.array(pts[-1]); d = unit(*(tip - np.array(pts[-2])))
    k.add("tip", tube([tip - d * 0.03, tip, tip + d * 0.022], [r * 0.86, r * 0.82, r * 0.5], seg=12), TIP, "head",
          fuse=False, glow=TIP)


def antenna(k, L):
    """A feathery antenna on each ear bone: a plume of serrated plate out of the crown, up, out and forward."""
    for s, side in ((1, "R"), (-1, "L")):
        root = np.array([0.026 * s, -0.19, 0.49])
        d = unit(0.75 * s, -0.35, 1.0)
        length = 0.135
        n = 13
        pts = []
        for i in range(n + 1):
            t = i / n
            w = 0.019 * (1 - 0.55 * t) * (1.0 if i % 2 == 0 else 0.45) + 0.005
            pts.append((t * length, w))
        outline = [(0.0, 0.0)] + pts + [(length + 0.008, 0.0)] + [(a, -w) for a, w in pts[::-1]]
        ex = d
        ez = np.cross(d, unit(0.5 * s, -1.0, 0.0)); ez /= np.linalg.norm(ez)    # face toward the front three-quarter
        k.add(f"antenna{side}", slab(outline, root, ex, ez, 0.011), "#3A3B42", "head", fuse=False, surface="fur")


def eye_open(u, v):
    """The great yellow-green eye: paler middle, a dark upright pupil toward the nose, a white glint."""
    c = np.tile(srgb(EYE), (len(u), 1))
    c[(u / 0.62) ** 2 + ((v + 0.05) / 0.62) ** 2 < 1] = srgb(EYELT)
    c[((u + 0.12) / 0.26) ** 2 + ((v + 0.05) / 0.5) ** 2 < 1] = srgb(PUPIL)
    c[((u + 0.36) / 0.16) ** 2 + ((v - 0.3) / 0.16) ** 2 < 1] = srgb(GLINT)
    c[u * u + v * v > 0.86 ** 2] = srgb(EYERIM)
    return c


def lay_eyes(k, L, state):
    lid, ink = srgb(GREYDK), srgb("#1A1A1E")
    brow = L["brow"]
    for s in (1, -1):
        c = np.array([L["eye_x"] * s * 1.12, L["eye_y"] - 0.035, L["eye_z"]])
        n = unit(0.55 * s, -1.0, 0.05)
        look = eye_look(state, eye_open, lid, ink, line=0.16)
        if state == "Open":
            def cut(u, v, f=look):
                col = f(u, v)
                edge = 0.3 + brow * u                    # high at the outer corner, low toward the nose
                col[v > edge] = lid
                col[np.abs(v - edge) < 0.09] = ink
                return col
            look = cut
        col = look if s > 0 else (lambda u, v, f=look: f(-u, v))
        k.decal(c, n, L["eye_half"], col, eps=0.002, rings=20, segs=56)


def board(tag):
    V = np.vstack([np.array([v.co[:] for v in o.data.vertices]) for o in bpy.data.objects
                   if o.type == "MESH" and not o.name.startswith("eyes.")])
    w, l, h = np.ptp(V[:, 0]), np.ptp(V[:, 1]), V[:, 2].max()
    sq = 1.3 * max(h, 0.85 * max(w, l)); sm = 0.853 * w + 0.522 * l
    t = math.radians(31.5); span = max(np.ptp(V[:, 0] * math.cos(t) + V[:, 1] * math.sin(t)), np.ptp(V[:, 0] * math.cos(t) - V[:, 1] * math.sin(t)))
    print(f"KIT: board {tag}: width {w:.3f} length {l:.3f} height {h:.3f} lowest {V[:, 2].min():.3f}; "
          f"four-corner sum {sm:.3f} of square {sq:.3f} ({sm / sq:.2f}); seen at 31.5 degrees {span:.3f} ({span / sq:.2f})")


def tantarel(src, out, L=LOOK, extras=None, tag="Tantarel"):
    k = Kit(src, coat=L["coat"])
    body(k, L)
    wing(k, "wing", (0.035, -0.02, 0.505), "wing{s}", L["wing_len"], L["wing_w"], L["wing_lift"], L["wing_sweep"],
         L["wing_fill"], L["wing_rim"], L["wing_glow"], rim_glow=L.get("rim_glow"))
    wing(k, "hindwing", (0.035, 0.03, 0.49), "wing{s}.001", L["hind_len"], L["hind_w"], L["hind_lift"], L["hind_sweep"],
         L["wing_fill"], L["wing_rim"], L["wing_glow"], rim_glow=L.get("rim_glow"))
    legs(k, L)
    proboscis(k, L)
    antenna(k, L)
    if extras:
        extras(k, L)
    k.build(voxel=0.0045, smooth=3, band=0.006, wband=0.03)
    board(tag)
    k.eye_states(lambda state: lay_eyes(k, L, state))
    k.export(out)


if __name__ == "__main__":
    tantarel(*args())
