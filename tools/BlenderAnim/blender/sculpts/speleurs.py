# Speleurs (Carpathia No. 10163) sculpted from nothing on the skeleton and clips of the game's own export of it
# (sculptkit.py):
#   blender --background --factory-startup --python sculpts/speleurs.py -- <the export's Speleurs.glb> <out.glb>
# Written to be grown from: pesterurs.py imports it (sibling("speleurs")) and keeps its frame: the domed head with its
# pale muzzle, the round ear with its dark lining, the sleepy eye under its heavy lid, the claw, the paw, the tufts of
# shaggy fur, the crust of calcite (lumpy fused masses with drips of short lobes, mottled in beige), the board check.
#
# The game has no sculptor of its own for Speleurs: its export is a quadruped generated by rule, of which only the
# bones, the clips and the size are taken.
#
# The design, from the project's picture (docs/art/reference/gemini/carpathia/10163-Speleurs.jpg): a stocky ancient
# bear cub standing on all fours, stone-grey fur, shaggy at the cheeks, the throat and the belly's edge. A big domed
# head some two fifths of the height, carried low in front; small round ears with a dark lining; a paler grey muzzle, a
# dark brown nose, a small open pout of a mouth; sleepy half-lidded eyes under brows raised at their inner ends, a
# bewildered, gentle look. Over the shoulders and the back a thick crust of pale mineral, white mottled with beige and
# a lavender grey, lumpy on top and running down the flanks in short drips. Thick short legs, broad paws, short pale
# claws, four to a paw; a stub of a tail.
# The skeleton: body (0, 0, 0.287), head (0, -0.17, 0.368), ears (+-0.088, -0.386, 0.65), legs (+-0.13, -0.175, 0.236),
# hinds (+-0.13, 0.175, 0.236), tail (0, 0.26, 0.348).
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np
from mathutils import Vector
from mathutils.bvhtree import BVHTree
from sculptkit import Kit, ell, tube, hull, srgb, inside, unit, boxy, lumpy, polygon, eye_look, args

FUR, FURDARK, MUZZLE, NOSE, MOUTH = "#7D7974", "#5E5A56", "#A49D94", "#4A3A34", "#2C2421"
CRUST, BEIGE, LAV, CLAW, LINING = "#ECE9E0", "#C8B6A3", "#D3CDC7", "#C1B9AC", "#4C4744"
INK, WHITE, IRIS, BROW = "#191514", "#EDE8E0", "#3E2E26", "#4A4541"


# --- the line's helpers ----------------------------------------------------------------------------------------------
def hit(shape, o, d):
    """Where a ray from o along d first meets a part's own mesh: a place on a part before the body is fused."""
    V, F = shape
    h = BVHTree.FromPolygons(V.tolist(), F).ray_cast(Vector(o), Vector(unit(*d)))
    return np.array(h[0])


def board(ob):
    """The game's board: a square of 1.3 x max(height, 0.85 x max(width, length)); four corners show 0.853 w + 0.522 l."""
    V = np.array([v.co[:] for v in ob.data.vertices])
    h, w, l = V[:, 2].max(), np.ptp(V[:, 0]), np.ptp(V[:, 1])
    sq = 1.3 * max(h, 0.85 * max(w, l))
    s = 0.853 * w + 0.522 * l
    print(f"BOARD: height {h:.3f} width {w:.3f} length {l:.3f}; corners {s:.3f} of square {sq:.3f} = {s / sq:.2f}")


def claw(k, name, base, d, length, width, bone, color=CLAW, curl=0.25):
    """A short claw: a flat-faced wedge from base along d, its tip bent down."""
    base, d = np.array(base, float), unit(*d)
    a = np.cross(d, (0, 0, 1.0))
    if np.linalg.norm(a) < 1e-3:
        a = np.array([1.0, 0, 0])
    a /= np.linalg.norm(a)
    b = np.cross(a, d)
    tip = base + d * length - b * (width * 0.3 + curl * length)
    mid = base + d * length * 0.55 - b * curl * length * 0.3
    k.add(name, hull([base + a * width + b * width * 0.8, base - a * width + b * width * 0.8,
                      base + a * width - b * width * 0.7, base - a * width - b * width * 0.7,
                      base - d * width, mid + a * width * 0.6 + b * width * 0.3, mid - a * width * 0.6 + b * width * 0.3,
                      mid - b * width * 0.5, tip]), color, bone, fuse=False, surface="shell")


def paw_claws(k, nm, c, fwd, spread, n, length, width, bone):
    """n claws along the front of a paw centred at c, pointing along fwd."""
    fwd = unit(*fwd)
    side = unit(*np.cross(fwd, (0, 0, 1.0)))
    for i in range(n):
        o = (i - (n - 1) / 2) * spread
        base = np.array(c) + side * o + fwd * (-0.25 * abs(i - (n - 1) / 2) * spread)
        claw(k, f"claw{nm}{i}", base, fwd + side * 0.15 * (i - (n - 1) / 2) - np.array([0, 0, 0.25]), length, width,
             bone)


def tuft(k, name, base, d, length, width, bone, color):
    """A lock of shaggy fur: a solid wedge from base along d, lifting clear of the coat at its tip."""
    base, d = np.array(base, float), unit(*d)
    a = np.cross(d, (0, 1.0, 0)) if abs(d[1]) < 0.9 else np.cross(d, (1.0, 0, 0))
    a /= np.linalg.norm(a)
    b = np.cross(a, d)
    k.add(name, hull([base + a * width + b * width * 0.55, base - a * width + b * width * 0.55,
                      base + a * width - b * width * 0.55, base - a * width - b * width * 0.55,
                      base - d * width * 0.6, base + d * length * 0.55 + a * width * 0.5,
                      base + d * length * 0.55 - a * width * 0.5, base + d * length]), color, bone, fuse=False,
          surface="fur")


def round_ear(k, c, r, n, bone, color, lining, half, eps=0.003):
    """A small round ear fused into the crown, a dark oval laid on its front (mirrored)."""
    c, n = np.array(c, float), unit(*n)
    k.add("ear", ell(c, r), color, bone, mirror=True)
    k.decal(hit(ell(c, r), c + n * 0.3, -n), n, half, lining, eps=eps, rings=10, segs=48, mirror=True)


def coat_edge(y0, y1, z_side, tongues):
    """A mask for the crust painted over the coat: everything over a line that runs at z_side down the flanks between
    y0 and y1, its edge hanging in tongues (y, depth, width; on +X with a positive depth's sign of side)."""
    def mask(P):
        x, y, z = P[:, 0], P[:, 1], P[:, 2]
        edge = np.full(len(P), float(z_side))
        for side, yt, depth, w in tongues:
            edge = edge - depth * np.exp(-((y - yt) / w) ** 2) * (np.sign(x) == side)
        ends = inside(y0 - y, 0.012) * inside(y - y1, 0.012)
        return inside(edge - z, 0.004) * ends
    return mask


def crust(k, blobs, drips, bone="body", seed=3, colour=CRUST, beige=BEIGE, lav=LAV, cover=None, cover_on=None, freq=1.0):
    """The crust of calcite: lumpy fused masses (centre, radii, bumps) and drips of short round lobes hanging from
    their edge (top point, bottom point, radius), and a coat of it painted over the fur below them (cover, a mask; its
    edge hangs in tongues), all mottled in beige and a lavender grey."""
    for i, (c, r, m) in enumerate(blobs):
        k.add(f"crust{i}", ell(c, r, deform=lumpy(m, m - 1, 0.1)), colour, bone)
    for i, (a, b, r) in enumerate(drips):
        a, b = np.array(a, float), np.array(b, float)
        k.add(f"crustdrip{i}", tube([a, (a + b) / 2 + (np.sign(a[0]) * 0.006, 0, 0), b], [r, r * 0.92, r * 0.8]),
              colour, bone)
    if cover is not None:
        k.paint(cover, colour, on=cover_on)
    rs = np.random.RandomState(seed)
    K = rs.normal(size=(3, 3)) * np.array([[38], [44], [33]]) * freq
    def mottle(P, cut):
        q = (np.sin(P @ K[0] + 1.3) + np.sin(P @ K[1] + 0.4) * 0.8 + np.sin(P @ K[2] + 2.0) * 0.6)
        return inside(cut - q, 0.12)
    whole = (lambda P: 1.0) if cover is None else cover
    k.paint(lambda P: mottle(P, -0.6), beige, on=["crust"])
    k.paint(lambda P: mottle(P * 1.3 + 0.5, -1.1), lav, on=["crust"])
    if cover is not None:
        k.paint(lambda P: mottle(P, -0.6) * whole(P), beige, on=cover_on)
        k.paint(lambda P: mottle(P * 1.3 + 0.5, -1.1) * whole(P), lav, on=cover_on)


# --- the sleepy eye: half lidded, the lid's edge a dark line, a dark iris under it, a glint -------------------------
CW, CI, CK, CG = srgb(WHITE), srgb(IRIS), srgb(INK), srgb("#FFFFFF")
EYE_OUT = [(-1.0, 0.05), (-0.5, 0.62), (0.2, 0.75), (0.85, 0.5), (1.0, 0.0), (0.7, -0.6), (0.0, -0.85),
           (-0.6, -0.6)]


def sleepy(lid_colour, lid=0.12, slope=-0.12):
    """The open eye of the line: the upper part under the lid (u outward), a dark iris below the lid's edge."""
    L = srgb(lid_colour)
    def look(u, v):
        c = np.tile(CW, (len(u), 1))
        c[((u + 0.0) / 0.62) ** 2 + ((v + 0.15) / 0.78) ** 2 < 1] = CI
        c[((u + 0.0) / 0.36) ** 2 + ((v + 0.2) / 0.45) ** 2 < 1] = CK
        c[((u - 0.2) / 0.15) ** 2 + ((v + 0.05) / 0.15) ** 2 < 1] = CG
        edge = lid + slope * u
        c[v > edge - 0.17] = CK
        c[v > edge] = L
        return c
    return look


def eye_layer(k, E, de, half, look, lid_colour, out=EYE_OUT):
    """lay(state) for the eye_states: an almond patch each side, hand-mirrored so the outline keeps its corners."""
    L = srgb(lid_colour)
    def lay(state):
        if state == "Fierce":
            def lk(uu, v):
                c = look(uu, v)
                c[v > -0.2 + 0.5 * uu] = CK
                c[v > -0.04 + 0.5 * uu] = L
                return c
        else:
            lk = eye_look(state, look, L, CK, line=0.2)
        for s in (1, -1):
            shape = polygon([(a * s, b) for a, b in out])
            col = lk if s > 0 else (lambda uu, v, f=lk: f(-uu, v))
            k.decal(np.array(E) * (s, 1, 1), np.array(de) * (s, 1, 1), half, col, eps=0.003, outline=shape, rings=20,
                    segs=56)
    return lay


def head(k, H, HR, muz, muz_r, colours, dome=(0.0, 0.0, 0.08), dome_r=(0.85, 0.8, 0.62), ear=None, mouth_open=True):
    """The domed head: a squared ball, a dome on its brow, the pale muzzle standing forward low on the face with a
    dark nose on its tip and the mouth under it. Returns the head's shape (for placing the eyes)."""
    fur, mz, nose, mouthc = colours
    HEAD = ell(H, HR, deform=boxy(2.3))
    k.add("head", HEAD, fur, "head")
    k.add("dome", ell(H + dome, np.array(HR) * dome_r), fur, "head")
    MUZ = ell(H + muz, muz_r)
    k.add("muzzle", MUZ, mz, "head")
    k.paint(lambda P: inside(np.linalg.norm((P - (H + muz)) / (np.array(muz_r) * 1.12), axis=1) - 1, 0.004)
            * (P[:, 1] < H[1] + muz[1] * 0.4), mz, on=["muzzle", "head"])
    NC = hit(MUZ, H + muz + (0, -0.4, muz_r[2] * 0.25), (0, 1, 0))
    k.add("nose", ell(NC + (0, 0.01, 0.004), (muz_r[0] * 0.5, muz_r[1] * 0.32, muz_r[2] * 0.38)), nose, "head",
          fuse=False, surface="skin")
    def mouth(u, v):
        c = np.tile(srgb(mz), (len(u), 1))
        if mouth_open:
            c[(u / 0.7) ** 2 + ((v + 0.05) / 0.7) ** 2 < 1] = srgb(mouthc)       # a small open pout
        else:
            c[(np.abs(v - (0.05 - 0.35 * u * u)) < 0.3) & (np.abs(u) < 0.88)] = srgb(mouthc)
        return c
    MC = hit(MUZ, H + muz + (0, -0.4, -muz_r[2] * 0.55), (0, 1, 0))
    k.decal(MC, unit(0, -1, -0.35), (muz_r[0] * 0.38, muz_r[2] * 0.26) if mouth_open else (muz_r[0] * 0.6, muz_r[2] * 0.2),
            mouth, eps=0.003, rings=10, segs=48)
    return HEAD


def brows(k, HEAD, H, at, d, half, colour, tilt):
    """Brows over the eyes, the inner ends raised by tilt (a worried look) or level (calm)."""
    for s in (1, -1):
        BC = hit(HEAD, H + (at[0] * s, -0.6, at[2]), (0, 1, 0))
        k.decal(BC, unit(d[0] * s, d[1], d[2]), half, colour, up=unit(tilt * s, 0, 1), eps=0.003, rings=8, segs=40)


# --- Speleurs --------------------------------------------------------------------------------------------------------
H = np.array([0.0, -0.395, 0.468])          # the head's middle (its bone at 0, -0.17, 0.368)
HR = np.array([0.158, 0.148, 0.158])
BODYPARTS = ["trunk", "chest", "rump", "hump", "neck", "shoulder", "fore", "haunch", "shin", "pawf", "pawh"]


def body(k):
    k.add("trunk", ell((0, 0.0, 0.35), (0.212, 0.33, 0.215)), FUR, "body")
    k.add("chest", ell((0, -0.23, 0.36), (0.195, 0.17, 0.205)), FUR, "body")
    k.add("rump", ell((0, 0.25, 0.39), (0.19, 0.14, 0.19)), FUR, "body")
    k.add("hump", ell((0, -0.12, 0.53), (0.19, 0.2, 0.13)), FUR, "body")
    k.add("neck", ell((0, -0.31, 0.46), (0.155, 0.13, 0.15)), FUR, "head")
    k.add("tail", ell((0, 0.385, 0.42), (0.04, 0.035, 0.035)), FUR, "tail")


def legs(k):
    """Thick short legs set wider than the shoulders, bent a little, the shoulders and haunches fused into the body."""
    for s, nm in ((1, "R"), (-1, "L")):
        m = np.array([s, 1, 1.0])
        k.add("shoulder" + nm, ell(np.array((0.155, -0.2, 0.36)) * m, (0.115, 0.135, 0.17)), FUR, "leg" + nm)
        k.add("fore" + nm, tube([np.array(p) * m for p in [(0.17, -0.2, 0.26), (0.19, -0.19, 0.15),
                                                           (0.2, -0.235, 0.09)]], [0.096, 0.09, 0.086]), FUR, "leg" + nm)
        k.add("pawf" + nm, ell(np.array((0.205, -0.265, 0.035)) * m, (0.088, 0.1, 0.038)), FURDARK, "leg" + nm)
        paw_claws(k, "f" + nm, np.array((0.205, -0.35, 0.045)) * m, (0, -1, 0), 0.034, 4, 0.04, 0.012, "leg" + nm)
        k.add("haunch" + nm, ell(np.array((0.15, 0.22, 0.37)) * m, (0.125, 0.16, 0.19)), FUR, "hind" + nm)
        k.add("shin" + nm, tube([np.array(p) * m for p in [(0.172, 0.24, 0.22), (0.185, 0.2, 0.09)]], [0.097, 0.088]),
              FUR, "hind" + nm)
        k.add("pawh" + nm, ell(np.array((0.188, 0.16, 0.035)) * m, (0.085, 0.1, 0.037)), FURDARK, "hind" + nm)
        paw_claws(k, "h" + nm, np.array((0.188, 0.075, 0.043)) * m, (0, -1, 0), 0.032, 4, 0.034, 0.011, "hind" + nm)
    # the paws a shade darker, the line round each leg's foot
    k.paint(lambda P: inside(P[:, 2] - 0.07, 0.006), FURDARK, on=["fore", "shin", "pawf", "pawh"])


def fur(k):
    """Shaggy locks at the cheeks, the throat and the belly's edge: the fur's outline."""
    locks = [((0.13, -0.42, 0.37), (0.75, 0.1, -0.55), 0.075), ((0.15, -0.36, 0.42), (0.85, 0.25, -0.3), 0.07),
             ((0.07, -0.47, 0.33), (0.35, -0.3, -0.85), 0.06), ((0.0, -0.4, 0.31), (0.0, -0.4, -0.9), 0.065),
             ((0.16, -0.3, 0.49), (0.8, 0.45, 0.1), 0.065), ((0.12, -0.31, 0.3), (0.45, -0.25, -0.85), 0.06),
             ((0.17, -0.05, 0.2), (0.4, 0.1, -0.9), 0.055), ((0.12, 0.1, 0.19), (0.3, 0.2, -0.95), 0.05),
             ((0.17, 0.3, 0.3), (0.55, 0.6, -0.55), 0.055)]
    for i, (b, d, l) in enumerate(locks):
        tuft(k, f"lock{i}", b, d, l + 0.02, 0.03, "head" if b[1] < -0.28 else "body", FUR)
        tuft(k, f"lockL{i}", (-b[0], b[1], b[2]), (-d[0], d[1], d[2]), l * 0.95 + 0.02, 0.03,
             "head" if b[1] < -0.28 else "body", FUR)


def speleurs(src, out):
    k = Kit(src, coat="fur")
    body(k)
    legs(k)
    fur(k)
    HEAD = head(k, H, HR, (0, -0.128, -0.07), (0.078, 0.07, 0.062), (FUR, MUZZLE, NOSE, MOUTH))
    round_ear(k, (0.105, -0.37, 0.615), (0.046, 0.026, 0.044), (0.25, -1, 0.15), "ear{s}", FUR, LINING,
              (0.024, 0.024))
    # The crust over the shoulders and the back, lumpy and highest over the shoulders, its drips down the flanks
    # (most on +X, the front camera's side)
    crust(k, [((0, -0.08, 0.585), (0.2, 0.24, 0.085), 6), ((0.02, 0.12, 0.565), (0.19, 0.17, 0.075), 5),
              ((0.03, -0.17, 0.625), (0.155, 0.12, 0.075), 5), ((0.06, -0.03, 0.64), (0.11, 0.12, 0.06), 4)],
          [((0.2, -0.06, 0.56), (0.215, -0.06, 0.49), 0.034), ((0.2, 0.12, 0.54), (0.21, 0.13, 0.48), 0.03),
           ((-0.2, -0.12, 0.55), (-0.21, -0.13, 0.5), 0.03)],
          cover=coat_edge(-0.27, 0.3, 0.505, [(1, -0.2, 0.07, 0.024), (1, -0.07, 0.12, 0.03), (1, 0.05, 0.06, 0.02),
                                              (1, 0.16, 0.09, 0.028), (-1, -0.14, 0.08, 0.028),
                                              (-1, 0.07, 0.07, 0.024), (-1, 0.22, 0.05, 0.02)]),
          cover_on=["trunk", "hump", "rump", "shoulder", "haunch", "crust"])
    brows(k, HEAD, H, (0.058, 0, 0.065), (0.42, -0.9, 0.25), (0.03, 0.009), BROW, tilt=0.45)
    E = hit(HEAD, H + (0.062, -0.6, 0.02), (0, 1, 0))
    lay = eye_layer(k, E, unit(0.42, -0.9, 0.1), (0.034, 0.03), sleepy(FURDARK, lid=0.15, slope=-0.12), FURDARK)
    k.build(voxel=0.0075, band=0.005, wband=0.06)
    board(k.ob)
    k.eye_states(lay)
    k.export(out)


if __name__ == "__main__":
    speleurs(*args())
