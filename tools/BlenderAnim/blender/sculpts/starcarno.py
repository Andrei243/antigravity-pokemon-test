# Starcarno sculpted from nothing on the skeleton and clips of the game's own export of it (sculptkit.py), grown from
# Starcel's script (starcel.py: its legs and feet, beak, glowering eye, folded wing with its scalloped rows and
# hanging primaries, tail and the way its down hangs in lobes):
#   blender --background --factory-startup --python sculpts/starcarno.py -- <the export's Starcarno.glb> <out.glb>
#
# Carpathia's delta heron (No. 10122, Flying/Water), from its picture (docs/art/reference/gemini/carpathia/
# 10122-Starcarno.jpg) and its brief (CP-dex-3-river-and-caves.md, 122). The game has no sculptor for it: its export
# is a body generated by rule, of which the skeleton, the clips and the size are kept and nothing of the shape.
# The design: Starcel grown tall and sleek: a long purple-grey body sloping back to a short tail on long tan legs;
# a long neck in an S, its front white streaked with long pale plumes hanging over the chest; a small head carried
# forward with a stern eye under its brow, the scruffy crest grown into a black crest swept back and two long black
# plumes trailing behind like ribbons; a dagger of a golden beak; the folded wing long, purple-grey with blue-grey
# rows and dark primaries hanging past the tail. The picture stands it on one leg in mid-step: the rest pose has
# both feet down. The reeds of the brief are scenery and are left out.
# The export stands its generated body 0.082 off the ground; the heron stands on it (see the report).
# The export's joints: body (0, 0, 0.388), tail (0, 0.198, 0.388), wings (+-0.175, -0.02, 0.466), head (0, -0.093,
# 0.481), legs (+-0.078, -0.02, 0.275).
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np
from sculptkit import Kit, ell, tube, blade, srgb, inside, unit, outward, args, sibling

sc = sibling("starcel")
spike = sc.spike

PURPLE, WING, BLUE, DARK = "#8C86AC", "#7F7BA6", "#6A82A2", "#3E4862"
PALE, HEADC, CREST, BEAK, FOOT = "#E8EAF2", "#97A4BC", "#262C3A", "#E2B648", "#D6B86C"


class Cfg(sc.Cfg):
    # a slim oval carried tilted 35 degrees, breast up and tail down
    BODY_C, BODY_R, BODY_ROT = (0.0, 0.04, 0.41), (0.082, 0.178, 0.076), (-35, 0, 0)
    # a long open S rising well above the body (a third of the height), the small head on top, the beak level
    HEAD_C, HEAD_R = np.array([0.0, -0.165, 0.712]), np.array([0.044, 0.058, 0.042])
    NECK = [(0.0, -0.095, 0.47), (0.0, -0.158, 0.51), (0.0, -0.152, 0.565), (0.0, -0.108, 0.62), (0.0, -0.11, 0.668),
            (0.0, -0.145, 0.7)]
    NECK_R = [0.044, 0.033, 0.029, 0.027, 0.028, 0.03]
    BEAK_LEN, BEAK_R, BEAK_DIR = 0.15, 0.0175, unit(0, -1, -0.08)
    EYE_DIR, EYE_HALF, PUPIL_R = unit(0.66, -0.56, 0.3), 0.021, 0.4
    BROW = (0.12, 0.42)
    HIP_Z, LEG_X, JOINT_Z, LEG_R = 0.33, 0.064, 0.17, (0.022, 0.0185, 0.0165)
    JOINT_FWD, STAGGER, KNOB = 0.045, 0.03, 1.36
    TOE_LEN, TOE_R = 0.085, 0.0115
    WING_C, WING_R, WING_ROT = (0.054, 0.06, 0.425), (0.033, 0.175, 0.066), (-35, 0, 0)
    MANTLE_C, MANTLE_R, MANTLE_ROT = (0.0, 0.065, 0.455), (0.056, 0.15, 0.036), (-35, 0, 0)
    PRIMARIES = 4
    # the wings' long dark feathers hanging down past the tail
    PRIM_ROOT, PRIM_TIP = (0.06, 0.14, 0.37), (0.045, 0.31, 0.17)
    TAIL_ROOT, TAIL_TIP = (0.0, 0.17, 0.33), (0.0, 0.27, 0.245)
    COLOURS = dict(grey=PURPLE, wing=WING, dark=DARK, pale=PALE, crown=CREST, edge=BLUE)


def head_colours(k, cfg):
    """The head grey-blue, its crown black, a white band from the beak's root under the eye and down the neck."""
    k.paint(lambda P: inside(np.linalg.norm((P - cfg.HEAD_C) / (cfg.HEAD_R * 1.3), axis=1) - 1, 0.02), HEADC,
            on=["head"])
    k.paint(lambda P: inside(cfg.HEAD_C[2] + 0.016 - P[:, 2], 0.004) * inside(np.linalg.norm(P - cfg.HEAD_C, axis=1)
                                                                              - 0.07, 0.004), CREST, on=["head"])
    # the white front of the neck and throat
    NZ = np.array([p[2] for p in cfg.NECK]); NY = np.array([p[1] for p in cfg.NECK])
    def front(P):
        x, y, z = P[:, 0], P[:, 1], P[:, 2]
        cy = np.interp(z, NZ, NY)                                # the neck's middle at that height
        return inside(y - cy + 0.004, 0.004) * inside(z - 0.7, 0.004) * inside(0.42 - z, 0.004)             * inside(np.abs(x) - 0.06, 0.004)
    k.paint(front, PALE, on=["neck", "body", "plume"])


def crest(k, cfg):
    """A black crest swept back from the crown, a few thick feathers, and the two long plumes trailing behind it,
    drooping, swept some 35 degrees toward +X so both cameras see their faces."""
    C, R = cfg.HEAD_C, cfg.HEAD_R
    for i, (a, up, ln) in enumerate(((-0.6, 0.9, 0.06), (-0.25, 1.0, 0.075), (0.1, 1.0, 0.08), (0.45, 0.9, 0.07),
                                     (0.8, 0.7, 0.055))):
        p, n = sc.on_ell(C, R, (0.7 * a, 0.35, 1.0))
        base = p - n * 0.008
        d = unit(0.35 * a + 0.12, 1.0, up * 0.7)
        k.add("crest", spike(base, base + d * ln, 0.026, 0.02, side=np.cross(d, (0, 1.0, 0)), at=0.3),
              CREST, "head", fuse=False, surface="fur")
    for j, (dx, ln, drop) in enumerate(((0.0, 0.3, 0.18), (0.032, 0.24, 0.25))):
        root = C + np.array([0.004 + dx, R[1] * 0.75, R[2] * 0.25 - 0.006 * j])
        pts = [root]
        for t in np.linspace(0.2, 1.0, 6):
            # back, a little out to +X, and down in a curve that steepens past the shoulders
            pts.append(root + np.array([0.07 * t + dx * t, ln * t, -drop * t ** 1.6]))
        r = [0.0125, 0.0135, 0.013, 0.0125, 0.0115, 0.01, 0.0075]
        d = unit(*(pts[-1] - pts[0]))
        flat = np.cross(d, (0, 0, 1.0))
        k.add("plume", outward(blade(pts, r, flat, 0.75)), CREST, "head", fuse=False, surface="fur")


def bib(k, cfg):
    """Long pale plumes hanging from the lower neck over the chest: lobes of the line's down, grown long."""
    for i, x in enumerate((-0.036, -0.012, 0.012, 0.036)):
        ln = (0.085, 0.115, 0.105, 0.08)[i]
        c = np.array([x, -0.168 + 0.4 * x * x, 0.49 - ln * 0.5])
        k.add("plume", ell(c, (0.015, 0.012, ln), rot=(-10, -x * 300, 0),
                           deform=lambda V: V * (1 - 0.5 * np.clip(-V[:, 2:3], 0, 1))),
              PALE if i % 2 else "#CDD3E2", "body")


def eyes(k, cfg):
    """Starcel's eye on the grown head, its lids the head's grey-blue."""
    ep, en = sc.on_ell(cfg.HEAD_C, cfg.HEAD_R, cfg.EYE_DIR)
    state_look = sc.heron_eye(cfg, CREST)
    def lay(state):
        k.decal(ep, en, (cfg.EYE_HALF, cfg.EYE_HALF), state_look(state, srgb(HEADC)), eps=0.0018, rings=20, segs=56,
                mirror=True)
    return lay


def starcarno(src, out_path, cfg=Cfg):
    k = Kit(src, coat="fur")
    sc.body(k, cfg)
    bib(k, cfg)
    head_colours(k, cfg)
    sc.wing(k, cfg)
    sc.tail(k, cfg)
    crest(k, cfg)
    sc.beak(k, cfg, colour=BEAK)
    for s, side in ((1, "R"), (-1, "L")):
        sc.leg(k, cfg, side, s, colour=FOOT)
    k.build(voxel=0.006, smooth=4, band=0.006, wband=0.05)
    sc.board(k)
    k.eye_states(eyes(k, cfg))
    k.export(out_path)


if __name__ == "__main__":
    starcarno(*args())
